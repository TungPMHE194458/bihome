CREATE TABLE APARTMENT (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID    NUMBER(19) NOT NULL,
    CODE           VARCHAR2(30 CHAR) NOT NULL,
    NAME           VARCHAR2(100 CHAR) NOT NULL,
    FLOOR_NO       VARCHAR2(10 CHAR) NOT NULL,
    BEDROOMS       NUMBER(3),
    ROOMS          NUMBER(3),
    AREA           NUMBER(10, 2) NOT NULL,
    TYPE           VARCHAR2(30 CHAR) NOT NULL,
    OWNERSHIP_TYPE VARCHAR2(30 CHAR) NOT NULL,
    USAGE_STATUS   VARCHAR2(30 CHAR) DEFAULT 'VACANT' NOT NULL,
    DESCRIPTION    VARCHAR2(4000 CHAR),
    STATUS         VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY     VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION        NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_APARTMENT PRIMARY KEY (ID),
    CONSTRAINT UK_APARTMENT_BUILDING_CODE UNIQUE (BUILDING_ID, CODE),
    CONSTRAINT FK_APARTMENT_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_APARTMENT_AREA CHECK (AREA > 0),
    CONSTRAINT CK_APARTMENT_ROOMS CHECK (NVL(BEDROOMS, 0) >= 0 AND NVL(ROOMS, 0) >= 0),
    CONSTRAINT CK_APARTMENT_TYPE CHECK (TYPE IN
        ('APARTMENT', 'PENTHOUSE', 'VILLA', 'DUPLEX', 'SHOPHOUSE', 'PREMISES', 'OFFICE')),
    CONSTRAINT CK_APARTMENT_OWNERSHIP CHECK (OWNERSHIP_TYPE IN ('RENT', 'OWN')),
    CONSTRAINT CK_APARTMENT_USAGE CHECK (USAGE_STATUS IN ('VACANT', 'OCCUPIED', 'RENOVATING')),
    CONSTRAINT CK_APARTMENT_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);
-- UK (BUILDING_ID, CODE) đã có index dẫn đầu bằng BUILDING_ID, đủ cho FK và lọc theo tòa.
CREATE INDEX IDX_APARTMENT_BUILDING_STATUS ON APARTMENT (BUILDING_ID, STATUS);
CREATE INDEX IDX_APARTMENT_BUILDING_FLOOR ON APARTMENT (BUILDING_ID, FLOOR_NO);
CREATE INDEX IDX_APARTMENT_TYPE ON APARTMENT (TYPE);
CREATE INDEX IDX_APARTMENT_USAGE ON APARTMENT (USAGE_STATUS);
CREATE INDEX IDX_APARTMENT_CREATED_AT ON APARTMENT (CREATED_AT);
CREATE INDEX IDX_APARTMENT_NAME_LOWER ON APARTMENT (LOWER(NAME));

COMMENT ON TABLE APARTMENT IS 'Căn hộ / đơn vị trong tòa nhà';
