CREATE TABLE APARTMENT_IMAGE (
    APARTMENT_ID NUMBER(19) NOT NULL,
    FILE_ID      NUMBER(19) NOT NULL,
    IS_COVER     NUMBER(1) DEFAULT 0 NOT NULL,
    SORT_ORDER   NUMBER(3) NOT NULL,
    CONSTRAINT PK_APARTMENT_IMAGE PRIMARY KEY (APARTMENT_ID, FILE_ID),
    CONSTRAINT FK_APARTMENT_IMAGE_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_APARTMENT_IMAGE_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT CK_APARTMENT_IMAGE_COVER CHECK (IS_COVER IN (0, 1))
);
CREATE INDEX IDX_APARTMENT_IMAGE_FILE ON APARTMENT_IMAGE (FILE_ID);
COMMENT ON TABLE APARTMENT_IMAGE IS 'Ảnh căn hộ, đúng một ảnh đại diện (IS_COVER = 1)';
