COMMENT ON COLUMN APARTMENT.BEDROOMS IS 'Số phòng ngủ';
COMMENT ON COLUMN APARTMENT.ROOMS IS 'Tổng số phòng';
COMMENT ON COLUMN APARTMENT.AREA IS 'Diện tích (m2), dùng tính phí quản lý';
COMMENT ON COLUMN APARTMENT.TYPE IS 'Loại: căn hộ, penthouse, villa, duplex, shophouse, mặt bằng, văn phòng';
