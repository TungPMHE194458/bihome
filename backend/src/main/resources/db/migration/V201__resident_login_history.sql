-- Lịch sử đăng nhập app cư dân, đối xứng với LOGIN_HISTORY của web/nhân viên. ACCOUNT_ID nullable: số điện thoại
-- không tồn tại (chưa từng có tài khoản) hoặc tài khoản đã bị BQL xoá sau đó vẫn giữ lại PHONE đã dùng để đăng nhập.
CREATE TABLE RESIDENT_LOGIN_HISTORY (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ACCOUNT_ID     NUMBER(19),
    PHONE          VARCHAR2(20 CHAR) NOT NULL,
    SUCCESS        NUMBER(1) NOT NULL,
    FAILURE_REASON VARCHAR2(50 CHAR),
    IP_ADDRESS     VARCHAR2(45 CHAR),
    USER_AGENT     VARCHAR2(500 CHAR),
    DEVICE_NAME    VARCHAR2(150 CHAR),
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESIDENT_LOGIN_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_RESIDENT_LOGIN_HISTORY_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES RESIDENT_ACCOUNT (ID)
        ON DELETE SET NULL,
    CONSTRAINT CK_RESIDENT_LOGIN_HISTORY_SUCCESS CHECK (SUCCESS IN (0, 1))
);
CREATE INDEX IDX_RESIDENT_LOGIN_HISTORY_ACCOUNT ON RESIDENT_LOGIN_HISTORY (ACCOUNT_ID);
CREATE INDEX IDX_RESIDENT_LOGIN_HISTORY_CREATED_AT ON RESIDENT_LOGIN_HISTORY (CREATED_AT);
COMMENT ON TABLE RESIDENT_LOGIN_HISTORY IS 'Lịch sử đăng nhập app cư dân (thành công và thất bại)';
