-- App cư dân: tài khoản đăng nhập (do BQL cấp), phiên đăng nhập trên thiết bị, push token và hộp thư.

CREATE TABLE RESIDENT_ACCOUNT (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RESIDENT_ID          NUMBER(19) NOT NULL,
    PHONE                VARCHAR2(20 CHAR) NOT NULL,
    PASSWORD_HASH        VARCHAR2(100 CHAR) NOT NULL,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    MUST_CHANGE_PASSWORD NUMBER(1) DEFAULT 1 NOT NULL,
    FAILED_LOGIN_COUNT   NUMBER(5) DEFAULT 0 NOT NULL,
    LOCKED_UNTIL         TIMESTAMP WITH TIME ZONE,
    PASSWORD_CHANGED_AT  TIMESTAMP WITH TIME ZONE,
    LAST_LOGIN_AT        TIMESTAMP WITH TIME ZONE,
    CREATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY           VARCHAR2(100 CHAR),
    UPDATED_BY           VARCHAR2(100 CHAR),
    VERSION              NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_RESIDENT_ACCOUNT PRIMARY KEY (ID),
    CONSTRAINT FK_RESIDENT_ACCOUNT_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID) ON DELETE CASCADE,
    CONSTRAINT UK_RESIDENT_ACCOUNT_RESIDENT UNIQUE (RESIDENT_ID),
    CONSTRAINT UK_RESIDENT_ACCOUNT_PHONE UNIQUE (PHONE),
    CONSTRAINT CK_RESIDENT_ACCOUNT_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED')),
    CONSTRAINT CK_RESIDENT_ACCOUNT_MUST_CHANGE CHECK (MUST_CHANGE_PASSWORD IN (0, 1))
);
COMMENT ON TABLE RESIDENT_ACCOUNT IS 'Tài khoản app cư dân (BQL cấp, đăng nhập bằng số điện thoại); xoá tài khoản = xoá dòng';
COMMENT ON COLUMN RESIDENT_ACCOUNT.PHONE IS 'Số điện thoại đăng nhập (0xxxxxxxxx), duy nhất toàn hệ thống';

CREATE TABLE RESIDENT_REFRESH_TOKEN (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ACCOUNT_ID   NUMBER(19) NOT NULL,
    TOKEN_HASH   VARCHAR2(64 CHAR) NOT NULL,
    DEVICE_NAME  VARCHAR2(150 CHAR),
    EXPIRES_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED_AT   TIMESTAMP WITH TIME ZONE,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_USED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_RESIDENT_REFRESH_TOKEN PRIMARY KEY (ID),
    CONSTRAINT FK_RESIDENT_REFRESH_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES RESIDENT_ACCOUNT (ID) ON DELETE CASCADE,
    CONSTRAINT UK_RESIDENT_REFRESH_HASH UNIQUE (TOKEN_HASH)
);
CREATE INDEX IDX_RESIDENT_REFRESH_ACCOUNT ON RESIDENT_REFRESH_TOKEN (ACCOUNT_ID);
COMMENT ON TABLE RESIDENT_REFRESH_TOKEN IS 'Refresh token của app cư dân (chỉ lưu SHA-256), xoay vòng mỗi lần làm mới';

CREATE TABLE RESIDENT_PUSH_TOKEN (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ACCOUNT_ID NUMBER(19) NOT NULL,
    TOKEN      VARCHAR2(255 CHAR) NOT NULL,
    PLATFORM   VARCHAR2(10 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESIDENT_PUSH_TOKEN PRIMARY KEY (ID),
    CONSTRAINT FK_RESIDENT_PUSH_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES RESIDENT_ACCOUNT (ID) ON DELETE CASCADE,
    CONSTRAINT UK_RESIDENT_PUSH_TOKEN UNIQUE (TOKEN),
    CONSTRAINT CK_RESIDENT_PUSH_PLATFORM CHECK (PLATFORM IN ('IOS', 'ANDROID', 'WEB'))
);
CREATE INDEX IDX_RESIDENT_PUSH_ACCOUNT ON RESIDENT_PUSH_TOKEN (ACCOUNT_ID);
COMMENT ON TABLE RESIDENT_PUSH_TOKEN IS 'Expo push token của thiết bị đã đăng nhập app cư dân';

CREATE TABLE RESIDENT_INBOX (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RESIDENT_ID NUMBER(19) NOT NULL,
    TYPE_CODE   VARCHAR2(30 CHAR) NOT NULL,
    TITLE       VARCHAR2(255 CHAR) NOT NULL,
    BODY        VARCHAR2(2000 CHAR),
    LINK        VARCHAR2(255 CHAR),
    READ_AT     TIMESTAMP WITH TIME ZONE,
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESIDENT_INBOX PRIMARY KEY (ID),
    CONSTRAINT FK_RESIDENT_INBOX_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RESIDENT_INBOX_TYPE CHECK (TYPE_CODE IN (
        'FEE_NOTICE', 'PAYMENT', 'TICKET', 'BOOKING', 'ANNOUNCEMENT', 'REMINDER', 'SOS', 'SYSTEM'))
);
CREATE INDEX IDX_RESIDENT_INBOX_RESIDENT ON RESIDENT_INBOX (RESIDENT_ID, CREATED_AT);
COMMENT ON TABLE RESIDENT_INBOX IS 'Hộp thư app cư dân (thông báo phí, thanh toán, yêu cầu, tiện ích, thông báo BQL, nhắc nhở)';
COMMENT ON COLUMN RESIDENT_INBOX.LINK IS 'Đường dẫn màn hình trong app, vd /fees/12, /tickets/5';
