-- App nhân viên (BiHome Quản lý): Expo push token của thiết bị đã đăng nhập bằng tài khoản người dùng hệ thống.
-- Thông báo trong hệ thống (NOTIFICATION) được đẩy thêm tới các thiết bị này.
CREATE TABLE USER_PUSH_TOKEN (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID    NUMBER(19) NOT NULL,
    TOKEN      VARCHAR2(255 CHAR) NOT NULL,
    PLATFORM   VARCHAR2(10 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_PUSH_TOKEN PRIMARY KEY (ID),
    CONSTRAINT FK_USER_PUSH_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (ID) ON DELETE CASCADE,
    CONSTRAINT UK_USER_PUSH_TOKEN UNIQUE (TOKEN),
    CONSTRAINT CK_USER_PUSH_PLATFORM CHECK (PLATFORM IN ('IOS', 'ANDROID', 'WEB'))
);
CREATE INDEX IDX_USER_PUSH_USER ON USER_PUSH_TOKEN (USER_ID);
COMMENT ON TABLE USER_PUSH_TOKEN IS 'Expo push token của thiết bị đã đăng nhập app nhân viên';
