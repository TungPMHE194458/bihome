CREATE TABLE REFRESH_TOKEN (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID       NUMBER(19) NOT NULL,
    TOKEN_HASH    VARCHAR2(64 CHAR) NOT NULL,
    FAMILY_ID     VARCHAR2(36 CHAR) NOT NULL,
    REMEMBER_ME   NUMBER(1) DEFAULT 0 NOT NULL,
    EXPIRES_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED_AT    TIMESTAMP WITH TIME ZONE,
    REVOKE_REASON VARCHAR2(30 CHAR),
    IP_ADDRESS    VARCHAR2(45 CHAR),
    USER_AGENT    VARCHAR2(500 CHAR),
    CREATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REFRESH_TOKEN PRIMARY KEY (ID),
    CONSTRAINT UK_REFRESH_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_REFRESH_TOKEN_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (ID),
    CONSTRAINT CK_REFRESH_TOKEN_REMEMBER CHECK (REMEMBER_ME IN (0, 1))
);
CREATE INDEX IDX_REFRESH_TOKEN_USER ON REFRESH_TOKEN (USER_ID);
CREATE INDEX IDX_REFRESH_TOKEN_FAMILY ON REFRESH_TOKEN (FAMILY_ID);
COMMENT ON TABLE REFRESH_TOKEN IS 'Refresh token (chỉ lưu SHA-256), xoay vòng theo family';
COMMENT ON COLUMN REFRESH_TOKEN.FAMILY_ID IS 'Chuỗi token sinh ra từ cùng một lần đăng nhập';

