CREATE TABLE ROLE (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODE        VARCHAR2(30 CHAR) NOT NULL,
    NAME        VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    IS_SYSTEM   NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION     NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ROLE PRIMARY KEY (ID),
    CONSTRAINT UK_ROLE_CODE UNIQUE (CODE),
    CONSTRAINT CK_ROLE_IS_SYSTEM CHECK (IS_SYSTEM IN (0, 1))
);
COMMENT ON TABLE ROLE IS 'Vai trò người dùng';
COMMENT ON COLUMN ROLE.CODE IS 'Mã vai trò (SUPER_ADMIN, BUILDING_MANAGER, STAFF, ACCOUNTANT, RESIDENT)';
COMMENT ON COLUMN ROLE.IS_SYSTEM IS 'Vai trò hệ thống, không được xoá';

CREATE TABLE PERMISSION (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODE        VARCHAR2(60 CHAR) NOT NULL,
    MODULE_CODE VARCHAR2(30 CHAR) NOT NULL,
    ACTION_CODE VARCHAR2(10 CHAR) NOT NULL,
    NAME        VARCHAR2(150 CHAR) NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION     NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PERMISSION PRIMARY KEY (ID),
    CONSTRAINT UK_PERMISSION_CODE UNIQUE (CODE),
    CONSTRAINT CK_PERMISSION_ACTION CHECK (ACTION_CODE IN ('READ', 'WRITE', 'DELETE', 'EXPORT'))
);
CREATE INDEX IDX_PERMISSION_MODULE ON PERMISSION (MODULE_CODE);
COMMENT ON TABLE PERMISSION IS 'Quyền dạng {MODULE}_{READ|WRITE|DELETE|EXPORT}';

CREATE TABLE ROLE_PERMISSION (
    ROLE_ID       NUMBER(19) NOT NULL,
    PERMISSION_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_ROLE_PERMISSION PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERMISSION_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLE (ID),
    CONSTRAINT FK_ROLE_PERMISSION_PERMISSION FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSION (ID)
);
CREATE INDEX IDX_ROLE_PERMISSION_PERMISSION ON ROLE_PERMISSION (PERMISSION_ID);

CREATE TABLE APP_USER (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USERNAME             VARCHAR2(50 CHAR) NOT NULL,
    EMAIL                VARCHAR2(150 CHAR) NOT NULL,
    PHONE                VARCHAR2(20 CHAR),
    PASSWORD_HASH        VARCHAR2(100 CHAR) NOT NULL,
    STATUS               VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    FAILED_LOGIN_COUNT   NUMBER(5) DEFAULT 0 NOT NULL,
    LOCKED_UNTIL         TIMESTAMP WITH TIME ZONE,
    LAST_LOGIN_AT        TIMESTAMP WITH TIME ZONE,
    PASSWORD_CHANGED_AT  TIMESTAMP WITH TIME ZONE,
    MUST_CHANGE_PASSWORD NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY           VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY           VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION              NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_APP_USER PRIMARY KEY (ID),
    CONSTRAINT UK_APP_USER_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_APP_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_APP_USER_PHONE UNIQUE (PHONE),
    CONSTRAINT CK_APP_USER_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'LOCKED')),
    CONSTRAINT CK_APP_USER_MUST_CHANGE CHECK (MUST_CHANGE_PASSWORD IN (0, 1))
);
CREATE INDEX IDX_APP_USER_STATUS ON APP_USER (STATUS);
CREATE INDEX IDX_APP_USER_CREATED_AT ON APP_USER (CREATED_AT);
COMMENT ON TABLE APP_USER IS 'Tài khoản đăng nhập hệ thống';
COMMENT ON COLUMN APP_USER.USERNAME IS 'Tên đăng nhập, lưu chữ thường';
COMMENT ON COLUMN APP_USER.EMAIL IS 'Email, lưu chữ thường';
COMMENT ON COLUMN APP_USER.STATUS IS 'ACTIVE hoạt động, INACTIVE ngừng hoạt động, LOCKED bị admin khoá';
COMMENT ON COLUMN APP_USER.FAILED_LOGIN_COUNT IS 'Số lần đăng nhập sai liên tiếp';
COMMENT ON COLUMN APP_USER.LOCKED_UNTIL IS 'Khoá tạm đến thời điểm này (sau 5 lần sai)';
COMMENT ON COLUMN APP_USER.PASSWORD_CHANGED_AT IS 'Access token cấp trước thời điểm này bị từ chối';
COMMENT ON COLUMN APP_USER.MUST_CHANGE_PASSWORD IS 'Bắt đổi mật khẩu (sau khi cấp mật khẩu tạm)';

CREATE TABLE USER_PROFILE (
    USER_ID        NUMBER(19) NOT NULL,
    FULL_NAME      VARCHAR2(150 CHAR) NOT NULL,
    AVATAR_FILE_ID NUMBER(19),
    GENDER         VARCHAR2(10 CHAR),
    DATE_OF_BIRTH  DATE,
    JOB_TITLE      VARCHAR2(100 CHAR),
    DEPARTMENT     VARCHAR2(100 CHAR),
    ADDRESS        VARCHAR2(500 CHAR),
    BIO            VARCHAR2(1000 CHAR),
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY     VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION        NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_USER_PROFILE PRIMARY KEY (USER_ID),
