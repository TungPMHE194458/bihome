CREATE TABLE SERVICE (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID     NUMBER(19) NOT NULL,
    CODE            VARCHAR2(30 CHAR) NOT NULL,
    NAME            VARCHAR2(150 CHAR) NOT NULL,
    SERVICE_TYPE_ID NUMBER(19) NOT NULL,
    UNIT_PRICE      NUMBER(12) NOT NULL,
    UNIT            VARCHAR2(30 CHAR) NOT NULL,
    DESCRIPTION     VARCHAR2(2000 CHAR),
    STATUS          VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY      VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY      VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION         NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SERVICE PRIMARY KEY (ID),
    CONSTRAINT FK_SERVICE_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_SERVICE_TYPE FOREIGN KEY (SERVICE_TYPE_ID) REFERENCES SERVICE_TYPE (ID),
    CONSTRAINT CK_SERVICE_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_SERVICE_PRICE CHECK (UNIT_PRICE >= 0)
);
CREATE UNIQUE INDEX UK_SERVICE_CODE ON SERVICE (BUILDING_ID, CODE);
CREATE INDEX IDX_SERVICE_TYPE ON SERVICE (SERVICE_TYPE_ID);
CREATE INDEX IDX_SERVICE_BUILDING_STATUS ON SERVICE (BUILDING_ID, STATUS);
CREATE INDEX IDX_SERVICE_CREATED_AT ON SERVICE (CREATED_AT);

COMMENT ON TABLE SERVICE IS 'Dịch vụ ban quản lý cung cấp cho căn hộ theo tòa nhà';
COMMENT ON COLUMN SERVICE.CODE IS 'Mã dịch vụ, duy nhất trong tòa; tự sinh DV + 4 số nếu bỏ trống';
COMMENT ON COLUMN SERVICE.UNIT_PRICE IS 'Đơn giá (VND) theo đơn vị tính';
COMMENT ON COLUMN SERVICE.UNIT IS 'Đơn vị tính (lần, giờ, m², kg...)';

CREATE TABLE SERVICE_IMAGE (
    SERVICE_ID NUMBER(19) NOT NULL,
    FILE_ID    NUMBER(19) NOT NULL,
    IS_COVER   NUMBER(1) DEFAULT 0 NOT NULL,
    SORT_ORDER NUMBER(3) NOT NULL,
    CONSTRAINT PK_SERVICE_IMAGE PRIMARY KEY (SERVICE_ID, FILE_ID),
    CONSTRAINT FK_SERVICE_IMAGE_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES SERVICE (ID),
    CONSTRAINT FK_SERVICE_IMAGE_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT CK_SERVICE_IMAGE_COVER CHECK (IS_COVER IN (0, 1))
);
CREATE INDEX IDX_SERVICE_IMAGE_FILE ON SERVICE_IMAGE (FILE_ID);
COMMENT ON TABLE SERVICE_IMAGE IS 'Ảnh dịch vụ, một ảnh đại diện (IS_COVER = 1)';

-- Voucher áp dụng cho tiện ích / dịch vụ cụ thể; không có dòng nào = mọi tiện ích / dịch vụ trong phạm vi.
CREATE TABLE VOUCHER_AMENITY (
    VOUCHER_ID NUMBER(19) NOT NULL,
    AMENITY_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_VOUCHER_AMENITY PRIMARY KEY (VOUCHER_ID, AMENITY_ID),
    CONSTRAINT FK_VOUCHER_AMENITY_VOUCHER FOREIGN KEY (VOUCHER_ID) REFERENCES VOUCHER (ID),
    CONSTRAINT FK_VOUCHER_AMENITY_AMENITY FOREIGN KEY (AMENITY_ID) REFERENCES AMENITY (ID)
);
CREATE INDEX IDX_VOUCHER_AMENITY_AMENITY ON VOUCHER_AMENITY (AMENITY_ID);
COMMENT ON TABLE VOUCHER_AMENITY IS 'Tiện ích cụ thể voucher áp dụng';

CREATE TABLE VOUCHER_SERVICE (
    VOUCHER_ID NUMBER(19) NOT NULL,
    SERVICE_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_VOUCHER_SERVICE PRIMARY KEY (VOUCHER_ID, SERVICE_ID),
    CONSTRAINT FK_VOUCHER_SERVICE_VOUCHER FOREIGN KEY (VOUCHER_ID) REFERENCES VOUCHER (ID),
    CONSTRAINT FK_VOUCHER_SERVICE_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES SERVICE (ID)
);
CREATE INDEX IDX_VOUCHER_SERVICE_SERVICE ON VOUCHER_SERVICE (SERVICE_ID);
COMMENT ON TABLE VOUCHER_SERVICE IS 'Dịch vụ cụ thể voucher áp dụng';
