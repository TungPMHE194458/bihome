CREATE TABLE TICKET_CATEGORY (
    ID                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME                  VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION           VARCHAR2(1000 CHAR),
    RESPONSE_SLA_HOURS    NUMBER(5) NOT NULL,
    RESOLUTION_SLA_HOURS  NUMBER(5) NOT NULL,
    DEFAULT_ASSIGNEE_ID   NUMBER(19),
    STATUS                VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY            VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY            VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION               NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TICKET_CATEGORY PRIMARY KEY (ID),
    CONSTRAINT FK_TICKET_CATEGORY_ASSIGNEE FOREIGN KEY (DEFAULT_ASSIGNEE_ID) REFERENCES APP_USER (ID),
    CONSTRAINT CK_TICKET_CATEGORY_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_TICKET_CATEGORY_SLA CHECK (RESPONSE_SLA_HOURS > 0 AND RESOLUTION_SLA_HOURS >= RESPONSE_SLA_HOURS)
);
-- Danh mục dùng chung cho mọi tòa; tên duy nhất không phân biệt hoa thường.
CREATE UNIQUE INDEX UK_TICKET_CATEGORY_NAME ON TICKET_CATEGORY (LOWER(NAME));
CREATE INDEX IDX_TICKET_CATEGORY_ASSIGNEE ON TICKET_CATEGORY (DEFAULT_ASSIGNEE_ID);
CREATE INDEX IDX_TICKET_CATEGORY_STATUS ON TICKET_CATEGORY (STATUS);

COMMENT ON TABLE TICKET_CATEGORY IS 'Danh mục yêu cầu & hỗ trợ (Điện, Nước, An ninh...) dùng chung cho mọi tòa';
COMMENT ON COLUMN TICKET_CATEGORY.RESPONSE_SLA_HOURS IS 'SLA phản hồi (giờ): hạn tiếp nhận tính từ lúc tạo';
COMMENT ON COLUMN TICKET_CATEGORY.RESOLUTION_SLA_HOURS IS 'SLA xử lý (giờ): hạn hoàn thành tính từ lúc tạo';
COMMENT ON COLUMN TICKET_CATEGORY.DEFAULT_ASSIGNEE_ID IS 'Người phụ trách mặc định (chỉ gán nếu người đó làm việc ở tòa của yêu cầu)';

