CREATE TABLE TICKET (
    ID                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID        NUMBER(19) NOT NULL,
    CODE               VARCHAR2(30 CHAR) NOT NULL,
    TITLE              VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION        VARCHAR2(4000 CHAR),
    CATEGORY_ID        NUMBER(19) NOT NULL,
    APARTMENT_ID       NUMBER(19),
    RESIDENT_ID        NUMBER(19),
    CHANNEL            VARCHAR2(20 CHAR) NOT NULL,
    PRIORITY           VARCHAR2(20 CHAR) DEFAULT 'MEDIUM' NOT NULL,
    ASSIGNEE_ID        NUMBER(19),
    STATUS             VARCHAR2(20 CHAR) DEFAULT 'NEW' NOT NULL,
    RESPONSE_DUE_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    RESOLUTION_DUE_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    RESPONDED_AT       TIMESTAMP WITH TIME ZONE,
    RESOLVED_AT        TIMESTAMP WITH TIME ZONE,
    CLOSED_AT          TIMESTAMP WITH TIME ZONE,
    RATING             NUMBER(1),
    RATING_COMMENT     VARCHAR2(1000 CHAR),
    CREATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY         VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY         VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION            NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TICKET PRIMARY KEY (ID),
    CONSTRAINT UK_TICKET_CODE UNIQUE (CODE),
    CONSTRAINT FK_TICKET_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_TICKET_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES TICKET_CATEGORY (ID),
    CONSTRAINT FK_TICKET_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_TICKET_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID),
    CONSTRAINT FK_TICKET_ASSIGNEE FOREIGN KEY (ASSIGNEE_ID) REFERENCES APP_USER (ID),
    CONSTRAINT CK_TICKET_CHANNEL CHECK (CHANNEL IN ('APP', 'HOTLINE', 'DIRECT')),
    CONSTRAINT CK_TICKET_PRIORITY CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT CK_TICKET_STATUS CHECK (STATUS IN ('NEW', 'RECEIVED', 'IN_PROGRESS', 'WAITING', 'DONE', 'CLOSED',
                                                  'CANCELLED')),
    CONSTRAINT CK_TICKET_RATING CHECK (RATING BETWEEN 1 AND 5)
);
CREATE INDEX IDX_TICKET_BUILDING_STATUS ON TICKET (BUILDING_ID, STATUS);
CREATE INDEX IDX_TICKET_CATEGORY ON TICKET (CATEGORY_ID);
CREATE INDEX IDX_TICKET_APARTMENT ON TICKET (APARTMENT_ID);
CREATE INDEX IDX_TICKET_RESIDENT ON TICKET (RESIDENT_ID);
CREATE INDEX IDX_TICKET_ASSIGNEE ON TICKET (ASSIGNEE_ID);
CREATE INDEX IDX_TICKET_RESOLUTION_DUE ON TICKET (RESOLUTION_DUE_AT);
CREATE INDEX IDX_TICKET_CREATED_AT ON TICKET (CREATED_AT);

COMMENT ON TABLE TICKET IS 'Yêu cầu và hỗ trợ của cư dân theo tòa nhà';
COMMENT ON COLUMN TICKET.CODE IS 'Mã yêu cầu YC-yyMMdd-xxx, tự sinh';
COMMENT ON COLUMN TICKET.CHANNEL IS 'Kênh tiếp nhận: APP | HOTLINE | DIRECT';
COMMENT ON COLUMN TICKET.STATUS IS 'NEW → RECEIVED → IN_PROGRESS ⇄ WAITING → DONE → CLOSED; CANCELLED (luồng hợp lệ trong TicketStatus)';
COMMENT ON COLUMN TICKET.RESPONSE_DUE_AT IS 'Hạn phản hồi = lúc tạo + SLA phản hồi của danh mục';
COMMENT ON COLUMN TICKET.RESOLUTION_DUE_AT IS 'Hạn xử lý = lúc tạo + SLA xử lý của danh mục';
COMMENT ON COLUMN TICKET.RESPONDED_AT IS 'Lần đầu rời trạng thái Mới';

-- Dòng thời gian: tạo, đổi trạng thái, phân công, bình luận (nội bộ / công khai).
CREATE TABLE TICKET_COMMENT (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    TICKET_ID    NUMBER(19) NOT NULL,
    ENTRY_TYPE   VARCHAR2(20 CHAR) NOT NULL,
    VISIBILITY   VARCHAR2(20 CHAR) DEFAULT 'INTERNAL' NOT NULL,
    CONTENT      VARCHAR2(4000 CHAR),
    FROM_STATUS  VARCHAR2(20 CHAR),
    TO_STATUS    VARCHAR2(20 CHAR),
    ASSIGNEE_ID  NUMBER(19),
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY   VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION      NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TICKET_COMMENT PRIMARY KEY (ID),
    CONSTRAINT FK_TICKET_COMMENT_TICKET FOREIGN KEY (TICKET_ID) REFERENCES TICKET (ID),
    CONSTRAINT FK_TICKET_COMMENT_ASSIGNEE FOREIGN KEY (ASSIGNEE_ID) REFERENCES APP_USER (ID),
    CONSTRAINT CK_TICKET_COMMENT_TYPE CHECK (ENTRY_TYPE IN ('CREATED', 'STATUS_CHANGE', 'ASSIGNMENT', 'COMMENT', 'RATING')),
    CONSTRAINT CK_TICKET_COMMENT_VISIBILITY CHECK (VISIBILITY IN ('INTERNAL', 'PUBLIC'))
);
CREATE INDEX IDX_TICKET_COMMENT_TICKET ON TICKET_COMMENT (TICKET_ID, CREATED_AT);
CREATE INDEX IDX_TICKET_COMMENT_ASSIGNEE ON TICKET_COMMENT (ASSIGNEE_ID);

COMMENT ON TABLE TICKET_COMMENT IS 'Dòng thời gian của yêu cầu: sự kiện và bình luận';
COMMENT ON COLUMN TICKET_COMMENT.ENTRY_TYPE IS 'CREATED | STATUS_CHANGE | ASSIGNMENT | COMMENT | RATING';
COMMENT ON COLUMN TICKET_COMMENT.VISIBILITY IS 'PUBLIC: cư dân xem được (app); INTERNAL: chỉ ban quản lý';

CREATE TABLE TICKET_ATTACHMENT (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    TICKET_ID   NUMBER(19) NOT NULL,
    COMMENT_ID  NUMBER(19),
    FILE_ID     NUMBER(19) NOT NULL,
    CONSTRAINT PK_TICKET_ATTACHMENT PRIMARY KEY (ID),
    CONSTRAINT FK_TICKET_ATTACHMENT_TICKET FOREIGN KEY (TICKET_ID) REFERENCES TICKET (ID),
    CONSTRAINT FK_TICKET_ATTACHMENT_COMMENT FOREIGN KEY (COMMENT_ID) REFERENCES TICKET_COMMENT (ID),
    CONSTRAINT FK_TICKET_ATTACHMENT_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT UK_TICKET_ATTACHMENT_FILE UNIQUE (FILE_ID)
);
CREATE INDEX IDX_TICKET_ATTACHMENT_TICKET ON TICKET_ATTACHMENT (TICKET_ID);
CREATE INDEX IDX_TICKET_ATTACHMENT_COMMENT ON TICKET_ATTACHMENT (COMMENT_ID);

COMMENT ON TABLE TICKET_ATTACHMENT IS 'Tệp đính kèm của yêu cầu (COMMENT_ID null) hoặc của một bình luận';
