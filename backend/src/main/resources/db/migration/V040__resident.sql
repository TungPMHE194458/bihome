CREATE TABLE RESIDENT (
    ID                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID        NUMBER(19) NOT NULL,
    CODE               VARCHAR2(20 CHAR) NOT NULL,
    FULL_NAME          VARCHAR2(150 CHAR) NOT NULL,
    PHONE              VARCHAR2(20 CHAR) NOT NULL,
    EMAIL              VARCHAR2(150 CHAR),
    GENDER             VARCHAR2(10 CHAR),
    DATE_OF_BIRTH      DATE,
    ID_TYPE            VARCHAR2(20 CHAR),
    ID_NUMBER          VARCHAR2(20 CHAR),
    ID_ISSUE_DATE      DATE,
    ID_ISSUE_PLACE     VARCHAR2(200 CHAR),
    NATIONALITY        VARCHAR2(100 CHAR),
    AVATAR_FILE_ID     NUMBER(19),
    APP_ACCOUNT_STATUS VARCHAR2(20 CHAR) DEFAULT 'NONE' NOT NULL,
    NOTE               VARCHAR2(1000 CHAR),
    CREATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY         VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY         VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION            NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_RESIDENT PRIMARY KEY (ID),
    CONSTRAINT FK_RESIDENT_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_RESIDENT_AVATAR FOREIGN KEY (AVATAR_FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT CK_RESIDENT_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT CK_RESIDENT_ID_TYPE CHECK (ID_TYPE IN ('CCCD', 'PASSPORT')),
    CONSTRAINT CK_RESIDENT_APP_ACCOUNT CHECK (APP_ACCOUNT_STATUS IN ('NONE', 'ACTIVE', 'LOCKED'))
);
-- Mã và số điện thoại duy nhất trong tòa (index dẫn đầu bằng BUILDING_ID, đủ cho FK).
CREATE UNIQUE INDEX UK_RESIDENT_CODE ON RESIDENT (BUILDING_ID, CODE);
CREATE UNIQUE INDEX UK_RESIDENT_PHONE ON RESIDENT (BUILDING_ID, PHONE);
CREATE INDEX IDX_RESIDENT_AVATAR ON RESIDENT (AVATAR_FILE_ID);
CREATE INDEX IDX_RESIDENT_APP_ACCOUNT ON RESIDENT (APP_ACCOUNT_STATUS);
CREATE INDEX IDX_RESIDENT_CREATED_AT ON RESIDENT (CREATED_AT);
CREATE INDEX IDX_RESIDENT_UPDATED_AT ON RESIDENT (UPDATED_AT);

COMMENT ON TABLE RESIDENT IS 'Cư dân theo tòa nhà; căn hộ đang/đã ở nằm ở APARTMENT_RESIDENT';
COMMENT ON COLUMN RESIDENT.CODE IS 'Mã cư dân, duy nhất trong tòa; tự sinh CD + 6 số nếu bỏ trống';
COMMENT ON COLUMN RESIDENT.PHONE IS 'Số di động đã chuẩn hoá dạng 0xxxxxxxxx, duy nhất trong tòa';
COMMENT ON COLUMN RESIDENT.ID_TYPE IS 'Loại giấy tờ: CCCD | PASSPORT';
COMMENT ON COLUMN RESIDENT.ID_NUMBER IS 'Số giấy tờ (đầy đủ); danh sách và file xuất chỉ hiện dạng che bớt';
COMMENT ON COLUMN RESIDENT.APP_ACCOUNT_STATUS IS 'Tài khoản app cư dân: NONE | ACTIVE | LOCKED';

CREATE TABLE APARTMENT_RESIDENT (
    ID                        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RESIDENT_ID               NUMBER(19) NOT NULL,
    APARTMENT_ID              NUMBER(19) NOT NULL,
    RESIDENT_ROLE             VARCHAR2(30 CHAR) NOT NULL,
    RELATIONSHIP              VARCHAR2(30 CHAR),
    IS_PRIMARY                NUMBER(1) DEFAULT 0 NOT NULL,
    MOVE_IN_DATE              DATE NOT NULL,
    MOVE_OUT_DATE             DATE,
    RESIDENCE_STATUS          VARCHAR2(30 CHAR) DEFAULT 'LIVING' NOT NULL,
    TEMP_RESIDENCE_REGISTERED NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT                TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT                TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY                VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY                VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION                   NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_APARTMENT_RESIDENT PRIMARY KEY (ID),
    CONSTRAINT FK_APARTMENT_RESIDENT_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID),
    CONSTRAINT FK_APARTMENT_RESIDENT_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT CK_APARTMENT_RESIDENT_ROLE CHECK (RESIDENT_ROLE IN ('OWNER', 'TENANT', 'FAMILY', 'GUEST')),
    CONSTRAINT CK_APARTMENT_RESIDENT_REL CHECK (RELATIONSHIP IN ('SPOUSE', 'CHILD', 'PARENT', 'OTHER')),
    CONSTRAINT CK_APARTMENT_RESIDENT_STATUS CHECK (RESIDENCE_STATUS IN ('LIVING', 'TEMP_ABSENT', 'MOVED_OUT')),
    CONSTRAINT CK_APARTMENT_RESIDENT_FLAGS CHECK (IS_PRIMARY IN (0, 1) AND TEMP_RESIDENCE_REGISTERED IN (0, 1)),
    -- Chủ hộ chính phải là Chủ sở hữu và chưa chuyển đi.
    CONSTRAINT CK_APARTMENT_RESIDENT_PRIMARY CHECK (
        IS_PRIMARY = 0 OR (RESIDENT_ROLE = 'OWNER' AND RESIDENCE_STATUS <> 'MOVED_OUT')),
    CONSTRAINT CK_APARTMENT_RESIDENT_DATES CHECK (MOVE_OUT_DATE IS NULL OR MOVE_OUT_DATE >= MOVE_IN_DATE)
);
CREATE INDEX IDX_APARTMENT_RESIDENT_RESIDENT ON APARTMENT_RESIDENT (RESIDENT_ID, RESIDENCE_STATUS);
CREATE INDEX IDX_APARTMENT_RESIDENT_APT ON APARTMENT_RESIDENT (APARTMENT_ID, RESIDENCE_STATUS);
CREATE INDEX IDX_APARTMENT_RESIDENT_MOVE_OUT ON APARTMENT_RESIDENT (MOVE_OUT_DATE);
-- Dòng không thoả điều kiện có khoá NULL nên không bị index (giống UK_ASSET_ITEM_ACTIVE_PLATE).
-- Mỗi căn tối đa một chủ hộ chính còn ở.
CREATE UNIQUE INDEX UK_APARTMENT_RESIDENT_PRIMARY ON APARTMENT_RESIDENT (
    CASE WHEN IS_PRIMARY = 1 AND RESIDENCE_STATUS <> 'MOVED_OUT' THEN APARTMENT_ID END
);
-- Một cư dân chỉ có một lần cư trú còn hiệu lực tại mỗi căn (lịch sử đã chuyển đi không giới hạn).
CREATE UNIQUE INDEX UK_APARTMENT_RESIDENT_ACTIVE ON APARTMENT_RESIDENT (
    CASE WHEN RESIDENCE_STATUS <> 'MOVED_OUT' THEN RESIDENT_ID END,
    CASE WHEN RESIDENCE_STATUS <> 'MOVED_OUT' THEN APARTMENT_ID END
);

COMMENT ON TABLE APARTMENT_RESIDENT IS 'Lần cư trú của cư dân tại căn hộ; giữ lại làm lịch sử khi chuyển đi';
COMMENT ON COLUMN APARTMENT_RESIDENT.RESIDENT_ROLE IS 'Vai trò tại căn hộ: OWNER | TENANT | FAMILY | GUEST';
COMMENT ON COLUMN APARTMENT_RESIDENT.RELATIONSHIP IS 'Quan hệ với chủ hộ: SPOUSE | CHILD | PARENT | OTHER';
COMMENT ON COLUMN APARTMENT_RESIDENT.IS_PRIMARY IS 'Chủ hộ chính (1); tối đa một người còn ở mỗi căn';
COMMENT ON COLUMN APARTMENT_RESIDENT.MOVE_OUT_DATE IS 'Ngày chuyển đi; ≤ hôm nay thì RESIDENCE_STATUS = MOVED_OUT';
COMMENT ON COLUMN APARTMENT_RESIDENT.TEMP_RESIDENCE_REGISTERED IS 'Đã đăng ký tạm trú (1) / chưa (0)';
