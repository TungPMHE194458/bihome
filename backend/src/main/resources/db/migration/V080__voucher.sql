CREATE TABLE VOUCHER (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID         NUMBER(19) NOT NULL,
    CODE                VARCHAR2(30 CHAR) NOT NULL,
    NAME                VARCHAR2(150 CHAR) NOT NULL,
    DESCRIPTION         VARCHAR2(1000 CHAR),
    DISCOUNT_TYPE       VARCHAR2(10 CHAR) NOT NULL,
    DISCOUNT_VALUE      NUMBER(12, 2) NOT NULL,
    MAX_DISCOUNT        NUMBER(12),
    APPLY_SCOPE         VARCHAR2(20 CHAR) DEFAULT 'ALL' NOT NULL,
    TOTAL_QUANTITY      NUMBER(10),
    USED_COUNT          NUMBER(10) DEFAULT 0 NOT NULL,
    PER_APARTMENT_LIMIT NUMBER(10),
    VALID_FROM          DATE NOT NULL,
    VALID_TO            DATE NOT NULL,
    STATUS              VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY          VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY          VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION             NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_VOUCHER PRIMARY KEY (ID),
    CONSTRAINT UK_VOUCHER_CODE UNIQUE (CODE),
    CONSTRAINT FK_VOUCHER_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_VOUCHER_TYPE CHECK (DISCOUNT_TYPE IN ('PERCENT', 'AMOUNT')),
    CONSTRAINT CK_VOUCHER_SCOPE CHECK (APPLY_SCOPE IN ('AMENITY', 'SERVICE', 'ALL')),
    CONSTRAINT CK_VOUCHER_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_VOUCHER_VALUE CHECK (DISCOUNT_VALUE > 0 AND (DISCOUNT_TYPE = 'AMOUNT' OR DISCOUNT_VALUE <= 100)),
    CONSTRAINT CK_VOUCHER_MAX CHECK (MAX_DISCOUNT IS NULL OR (DISCOUNT_TYPE = 'PERCENT' AND MAX_DISCOUNT > 0)),
    CONSTRAINT CK_VOUCHER_QUANTITY CHECK (TOTAL_QUANTITY IS NULL OR TOTAL_QUANTITY >= USED_COUNT),
    CONSTRAINT CK_VOUCHER_LIMIT CHECK (PER_APARTMENT_LIMIT IS NULL OR PER_APARTMENT_LIMIT > 0),
    CONSTRAINT CK_VOUCHER_DATES CHECK (VALID_TO >= VALID_FROM)
);
CREATE INDEX IDX_VOUCHER_BUILDING_STATUS ON VOUCHER (BUILDING_ID, STATUS);
CREATE INDEX IDX_VOUCHER_VALID ON VOUCHER (VALID_FROM, VALID_TO);
CREATE INDEX IDX_VOUCHER_CREATED_AT ON VOUCHER (CREATED_AT);

COMMENT ON TABLE VOUCHER IS 'Voucher giảm giá tiện ích / dịch vụ theo tòa nhà';
COMMENT ON COLUMN VOUCHER.CODE IS 'Mã voucher in hoa, duy nhất toàn hệ thống';
COMMENT ON COLUMN VOUCHER.DISCOUNT_TYPE IS 'PERCENT: giảm % (1–100) | AMOUNT: giảm số tiền (VND)';
COMMENT ON COLUMN VOUCHER.MAX_DISCOUNT IS 'Giảm tối đa (VND), chỉ với PERCENT';
COMMENT ON COLUMN VOUCHER.APPLY_SCOPE IS 'Áp dụng cho: AMENITY | SERVICE | ALL (danh sách tiện ích/dịch vụ cụ thể bổ sung ở module Tiện ích)';
COMMENT ON COLUMN VOUCHER.TOTAL_QUANTITY IS 'Tổng số lượt; NULL = không giới hạn';
COMMENT ON COLUMN VOUCHER.USED_COUNT IS 'Số lượt đã dùng (cập nhật khi đặt tiện ích / dịch vụ)';
COMMENT ON COLUMN VOUCHER.PER_APARTMENT_LIMIT IS 'Số lượt tối đa mỗi căn hộ; NULL = không giới hạn';
