-- Lịch sử hoạt động, thông báo trong hệ thống và thông báo do Ban quản lý soạn gửi.

-- Ghi trực tiếp bằng JDBC từ listener Hibernate (cùng transaction với thao tác nghiệp vụ), chỉ đọc qua API.
CREATE TABLE AUDIT_LOG (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    OCCURRED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ACTOR_ID       NUMBER(19),
    ACTOR_USERNAME VARCHAR2(100 CHAR) NOT NULL,
    ACTION         VARCHAR2(20 CHAR) NOT NULL,
    MODULE_CODE    VARCHAR2(30 CHAR) NOT NULL,
    ENTITY_TYPE    VARCHAR2(40 CHAR) NOT NULL,
    ENTITY_ID      VARCHAR2(40 CHAR) NOT NULL,
    ENTITY_LABEL   VARCHAR2(300 CHAR),
    BUILDING_ID    NUMBER(19),
    CHANGES        CLOB,
    IP_ADDRESS     VARCHAR2(45 CHAR),
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (ID),
    CONSTRAINT CK_AUDIT_LOG_ACTION CHECK (ACTION IN ('CREATE', 'UPDATE', 'STATUS_CHANGE', 'DELETE'))
);
CREATE INDEX IDX_AUDIT_LOG_OCCURRED ON AUDIT_LOG (OCCURRED_AT);
CREATE INDEX IDX_AUDIT_LOG_BUILDING ON AUDIT_LOG (BUILDING_ID, OCCURRED_AT);
CREATE INDEX IDX_AUDIT_LOG_MODULE ON AUDIT_LOG (MODULE_CODE, OCCURRED_AT);
CREATE INDEX IDX_AUDIT_LOG_ENTITY ON AUDIT_LOG (ENTITY_TYPE, ENTITY_ID);
CREATE INDEX IDX_AUDIT_LOG_ACTOR ON AUDIT_LOG (ACTOR_USERNAME);
COMMENT ON TABLE AUDIT_LOG IS 'Lịch sử hoạt động: ai, làm gì, với đối tượng nào, lúc nào';
COMMENT ON COLUMN AUDIT_LOG.ACTOR_ID IS 'Người thao tác (không FK để giữ lịch sử khi xoá người dùng); null = hệ thống';
COMMENT ON COLUMN AUDIT_LOG.MODULE_CODE IS 'Mã module theo permission (APARTMENT, TICKET...)';
COMMENT ON COLUMN AUDIT_LOG.ENTITY_TYPE IS 'Loại đối tượng (APARTMENT, TICKET_CATEGORY...)';
COMMENT ON COLUMN AUDIT_LOG.ENTITY_LABEL IS 'Mã / tên đối tượng tại thời điểm thao tác';
COMMENT ON COLUMN AUDIT_LOG.BUILDING_ID IS 'Tòa nhà của đối tượng (không FK); null = dữ liệu dùng chung';
COMMENT ON COLUMN AUDIT_LOG.CHANGES IS 'JSON [{field, oldValue, newValue}] của các trường thay đổi; trường nhạy cảm bị che';

CREATE TABLE ANNOUNCEMENT (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID     NUMBER(19) NOT NULL,
    TITLE           VARCHAR2(200 CHAR) NOT NULL,
    CONTENT         VARCHAR2(4000 CHAR) NOT NULL,
    CATEGORY        VARCHAR2(20 CHAR) NOT NULL,
    AUDIENCE        VARCHAR2(20 CHAR) NOT NULL,
    STATUS          VARCHAR2(20 CHAR) NOT NULL,
    SCHEDULED_AT    TIMESTAMP WITH TIME ZONE,
    SENT_AT         TIMESTAMP WITH TIME ZONE,
    SENT_BY         VARCHAR2(100 CHAR),
    STAFF_COUNT     NUMBER(10) DEFAULT 0 NOT NULL,
    RESIDENT_COUNT  NUMBER(10) DEFAULT 0 NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY      VARCHAR2(100 CHAR),
    UPDATED_BY      VARCHAR2(100 CHAR),
    VERSION         NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ANNOUNCEMENT PRIMARY KEY (ID),
    CONSTRAINT FK_ANNOUNCEMENT_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_ANNOUNCEMENT_CATEGORY CHECK (CATEGORY IN ('GENERAL', 'MAINTENANCE', 'EVENT', 'FEE', 'EMERGENCY')),
    CONSTRAINT CK_ANNOUNCEMENT_AUDIENCE CHECK (AUDIENCE IN ('STAFF', 'RESIDENT', 'ALL')),
    CONSTRAINT CK_ANNOUNCEMENT_STATUS CHECK (STATUS IN ('DRAFT', 'SCHEDULED', 'SENT')),
    CONSTRAINT CK_ANNOUNCEMENT_SCHEDULE CHECK (STATUS <> 'SCHEDULED' OR SCHEDULED_AT IS NOT NULL),
    CONSTRAINT CK_ANNOUNCEMENT_SENT CHECK (STATUS <> 'SENT' OR SENT_AT IS NOT NULL)
);
CREATE INDEX IDX_ANNOUNCEMENT_BUILDING ON ANNOUNCEMENT (BUILDING_ID, STATUS);
CREATE INDEX IDX_ANNOUNCEMENT_SCHEDULED ON ANNOUNCEMENT (STATUS, SCHEDULED_AT);
CREATE INDEX IDX_ANNOUNCEMENT_CREATED ON ANNOUNCEMENT (CREATED_AT);
COMMENT ON TABLE ANNOUNCEMENT IS 'Thông báo Ban quản lý soạn gửi nhân viên / cư dân của tòa';
COMMENT ON COLUMN ANNOUNCEMENT.AUDIENCE IS 'Đối tượng nhận: STAFF nhân viên tòa, RESIDENT cư dân (nhận qua app), ALL cả hai';
COMMENT ON COLUMN ANNOUNCEMENT.STATUS IS 'DRAFT nháp, SCHEDULED hẹn giờ gửi, SENT đã gửi';
COMMENT ON COLUMN ANNOUNCEMENT.STAFF_COUNT IS 'Số nhân viên đã nhận thông báo trong hệ thống lúc gửi';
COMMENT ON COLUMN ANNOUNCEMENT.RESIDENT_COUNT IS 'Số cư dân đang ở tại thời điểm gửi (nhận qua app cư dân)';

CREATE TABLE ANNOUNCEMENT_ATTACHMENT (
    ANNOUNCEMENT_ID NUMBER(19) NOT NULL,
    POSITION        NUMBER(5) NOT NULL,
    FILE_ID         NUMBER(19) NOT NULL,
    CONSTRAINT PK_ANNOUNCEMENT_ATTACHMENT PRIMARY KEY (ANNOUNCEMENT_ID, POSITION),
    CONSTRAINT FK_ANNOUNCEMENT_ATT_ANN FOREIGN KEY (ANNOUNCEMENT_ID) REFERENCES ANNOUNCEMENT (ID),
    CONSTRAINT FK_ANNOUNCEMENT_ATT_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID)
);
CREATE INDEX IDX_ANNOUNCEMENT_ATT_FILE ON ANNOUNCEMENT_ATTACHMENT (FILE_ID);

-- Thông báo trong hệ thống cho từng người dùng (chuông trên header).
CREATE TABLE NOTIFICATION (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RECIPIENT_ID NUMBER(19) NOT NULL,
    BUILDING_ID  NUMBER(19),
    TYPE_CODE    VARCHAR2(30 CHAR) NOT NULL,
    TITLE        VARCHAR2(200 CHAR) NOT NULL,
    BODY         VARCHAR2(1000 CHAR),
    LINK         VARCHAR2(300 CHAR),
    READ_AT      TIMESTAMP WITH TIME ZONE,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICATION PRIMARY KEY (ID),
    CONSTRAINT FK_NOTIFICATION_RECIPIENT FOREIGN KEY (RECIPIENT_ID) REFERENCES APP_USER (ID),
    CONSTRAINT FK_NOTIFICATION_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_NOTIFICATION_TYPE CHECK (TYPE_CODE IN (
        'TICKET_CREATED', 'TICKET_ASSIGNED', 'TICKET_STATUS', 'TICKET_COMMENT', 'ANNOUNCEMENT', 'SYSTEM'))
);
CREATE INDEX IDX_NOTIFICATION_RECIPIENT ON NOTIFICATION (RECIPIENT_ID, CREATED_AT);
CREATE INDEX IDX_NOTIFICATION_UNREAD ON NOTIFICATION (RECIPIENT_ID, READ_AT);
CREATE INDEX IDX_NOTIFICATION_BUILDING ON NOTIFICATION (BUILDING_ID);
COMMENT ON TABLE NOTIFICATION IS 'Thông báo trong hệ thống của từng người dùng (chuông trên header)';
COMMENT ON COLUMN NOTIFICATION.LINK IS 'Đường dẫn FE mở khi bấm thông báo';
COMMENT ON COLUMN NOTIFICATION.READ_AT IS 'Thời điểm đánh dấu đã đọc; null = chưa đọc';

