CREATE TABLE AMENITY (
    ID                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID       NUMBER(19) NOT NULL,
    CODE              VARCHAR2(30 CHAR) NOT NULL,
    NAME              VARCHAR2(150 CHAR) NOT NULL,
    LOCATION          VARCHAR2(200 CHAR),
    CAPACITY          NUMBER(5) NOT NULL,
    OPEN_TIME         VARCHAR2(5 CHAR) NOT NULL,
    CLOSE_TIME        VARCHAR2(5 CHAR) NOT NULL,
    RULES             VARCHAR2(4000 CHAR),
    REQUIRES_APPROVAL NUMBER(1) DEFAULT 0 NOT NULL,
    STATUS            VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY        VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY        VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION           NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_AMENITY PRIMARY KEY (ID),
    CONSTRAINT UK_AMENITY_CODE UNIQUE (CODE),
    CONSTRAINT FK_AMENITY_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_AMENITY_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_AMENITY_CAPACITY CHECK (CAPACITY > 0),
    CONSTRAINT CK_AMENITY_APPROVAL CHECK (REQUIRES_APPROVAL IN (0, 1)),
    CONSTRAINT CK_AMENITY_HOURS CHECK (REGEXP_LIKE(OPEN_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
        AND REGEXP_LIKE(CLOSE_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$') AND CLOSE_TIME > OPEN_TIME)
);
CREATE INDEX IDX_AMENITY_BUILDING_STATUS ON AMENITY (BUILDING_ID, STATUS);
CREATE INDEX IDX_AMENITY_CREATED_AT ON AMENITY (CREATED_AT);

COMMENT ON TABLE AMENITY IS 'Tiện ích của tòa nhà (hồ bơi, phòng gym, BBQ...)';
COMMENT ON COLUMN AMENITY.CODE IS 'Mã tiện ích in hoa, duy nhất toàn hệ thống';
COMMENT ON COLUMN AMENITY.CAPACITY IS 'Sức chứa (số người cùng lúc); khung giờ có thể đặt sức chứa riêng';
COMMENT ON COLUMN AMENITY.OPEN_TIME IS 'Giờ mở cửa HH:mm';
COMMENT ON COLUMN AMENITY.CLOSE_TIME IS 'Giờ đóng cửa HH:mm (sau giờ mở cửa, trong cùng ngày)';
COMMENT ON COLUMN AMENITY.REQUIRES_APPROVAL IS 'Đăng ký cần ban quản lý duyệt (1) / tự duyệt (0)';

CREATE TABLE AMENITY_IMAGE (
    AMENITY_ID NUMBER(19) NOT NULL,
    FILE_ID    NUMBER(19) NOT NULL,
    IS_COVER   NUMBER(1) DEFAULT 0 NOT NULL,
    SORT_ORDER NUMBER(3) NOT NULL,
    CONSTRAINT PK_AMENITY_IMAGE PRIMARY KEY (AMENITY_ID, FILE_ID),
    CONSTRAINT FK_AMENITY_IMAGE_AMENITY FOREIGN KEY (AMENITY_ID) REFERENCES AMENITY (ID),
    CONSTRAINT FK_AMENITY_IMAGE_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT CK_AMENITY_IMAGE_COVER CHECK (IS_COVER IN (0, 1))
);
CREATE INDEX IDX_AMENITY_IMAGE_FILE ON AMENITY_IMAGE (FILE_ID);
COMMENT ON TABLE AMENITY_IMAGE IS 'Ảnh tiện ích, một ảnh đại diện (IS_COVER = 1)';

-- Cấu hình đặt chỗ, 1–1 với tiện ích (khoá chính = AMENITY_ID).
CREATE TABLE AMENITY_CONFIG (
    AMENITY_ID            NUMBER(19) NOT NULL,
    SLOT_MINUTES          NUMBER(4) DEFAULT 60 NOT NULL,
    MAX_BOOKINGS_PER_WEEK NUMBER(3),
    MAX_ADVANCE_DAYS      NUMBER(3) DEFAULT 7 NOT NULL,
    FREE_CANCEL_HOURS     NUMBER(3) DEFAULT 2 NOT NULL,
    CREATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY            VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY            VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION               NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_AMENITY_CONFIG PRIMARY KEY (AMENITY_ID),
    CONSTRAINT FK_AMENITY_CONFIG_AMENITY FOREIGN KEY (AMENITY_ID) REFERENCES AMENITY (ID),
    CONSTRAINT CK_AMENITY_CONFIG_SLOT CHECK (SLOT_MINUTES BETWEEN 15 AND 720),
    CONSTRAINT CK_AMENITY_CONFIG_LIMITS CHECK ((MAX_BOOKINGS_PER_WEEK IS NULL OR MAX_BOOKINGS_PER_WEEK > 0)
        AND MAX_ADVANCE_DAYS BETWEEN 1 AND 365 AND FREE_CANCEL_HOURS BETWEEN 0 AND 720)
);
COMMENT ON TABLE AMENITY_CONFIG IS 'Cấu hình đặt tiện ích: thời lượng lượt, giới hạn, đặt trước, huỷ miễn phí';
COMMENT ON COLUMN AMENITY_CONFIG.SLOT_MINUTES IS 'Thời lượng mỗi lượt (phút), dùng để sinh khung giờ';
COMMENT ON COLUMN AMENITY_CONFIG.MAX_BOOKINGS_PER_WEEK IS 'Số lượt tối đa mỗi căn hộ / tuần; NULL = không giới hạn';
COMMENT ON COLUMN AMENITY_CONFIG.MAX_ADVANCE_DAYS IS 'Được đặt trước tối đa N ngày';
COMMENT ON COLUMN AMENITY_CONFIG.FREE_CANCEL_HOURS IS 'Huỷ miễn phí nếu trước giờ sử dụng ít nhất X giờ';

CREATE TABLE AMENITY_SLOT (
    AMENITY_ID  NUMBER(19) NOT NULL,
    DAY_OF_WEEK NUMBER(1) NOT NULL,
    START_TIME  VARCHAR2(5 CHAR) NOT NULL,
    END_TIME    VARCHAR2(5 CHAR) NOT NULL,
    CAPACITY    NUMBER(5),
    CONSTRAINT PK_AMENITY_SLOT PRIMARY KEY (AMENITY_ID, DAY_OF_WEEK, START_TIME),
    CONSTRAINT FK_AMENITY_SLOT_CONFIG FOREIGN KEY (AMENITY_ID) REFERENCES AMENITY_CONFIG (AMENITY_ID),
    CONSTRAINT CK_AMENITY_SLOT_DAY CHECK (DAY_OF_WEEK BETWEEN 1 AND 7),
    CONSTRAINT CK_AMENITY_SLOT_TIME CHECK (END_TIME > START_TIME),
    CONSTRAINT CK_AMENITY_SLOT_CAPACITY CHECK (CAPACITY IS NULL OR CAPACITY > 0)
);
COMMENT ON TABLE AMENITY_SLOT IS 'Khung giờ mở đặt theo thứ trong tuần (1 = Thứ 2 … 7 = Chủ nhật)';
COMMENT ON COLUMN AMENITY_SLOT.CAPACITY IS 'Sức chứa riêng của khung; NULL = theo sức chứa tiện ích';

CREATE TABLE AMENITY_PRICE (
    AMENITY_ID NUMBER(19) NOT NULL,
    DAY_TYPE   VARCHAR2(10 CHAR) NOT NULL,
    START_TIME VARCHAR2(5 CHAR) NOT NULL,
    END_TIME   VARCHAR2(5 CHAR) NOT NULL,
    PRICE      NUMBER(12) NOT NULL,
    PRICE_UNIT VARCHAR2(20 CHAR) DEFAULT 'PER_BOOKING' NOT NULL,
    CONSTRAINT PK_AMENITY_PRICE PRIMARY KEY (AMENITY_ID, DAY_TYPE, START_TIME),
    CONSTRAINT FK_AMENITY_PRICE_CONFIG FOREIGN KEY (AMENITY_ID) REFERENCES AMENITY_CONFIG (AMENITY_ID),
    CONSTRAINT CK_AMENITY_PRICE_DAY CHECK (DAY_TYPE IN ('WEEKDAY', 'WEEKEND')),
    CONSTRAINT CK_AMENITY_PRICE_UNIT CHECK (PRICE_UNIT IN ('PER_BOOKING', 'PER_PERSON')),
    CONSTRAINT CK_AMENITY_PRICE_VALUE CHECK (PRICE >= 0),
    CONSTRAINT CK_AMENITY_PRICE_TIME CHECK (END_TIME > START_TIME)
);
COMMENT ON TABLE AMENITY_PRICE IS 'Giá theo khung giờ: lượt bắt đầu trong [START_TIME, END_TIME) của loại ngày; không khớp = miễn phí';
COMMENT ON COLUMN AMENITY_PRICE.DAY_TYPE IS 'WEEKDAY (Thứ 2–6) | WEEKEND (Thứ 7, Chủ nhật)';
COMMENT ON COLUMN AMENITY_PRICE.PRICE_UNIT IS 'PER_BOOKING: mỗi lượt | PER_PERSON: mỗi người';

CREATE TABLE AMENITY_MAINTENANCE (
    AMENITY_ID NUMBER(19) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE   DATE NOT NULL,
    REASON     VARCHAR2(500 CHAR),
    CONSTRAINT PK_AMENITY_MAINTENANCE PRIMARY KEY (AMENITY_ID, START_DATE),
    CONSTRAINT FK_AMENITY_MAINTENANCE_CONFIG FOREIGN KEY (AMENITY_ID) REFERENCES AMENITY_CONFIG (AMENITY_ID),
    CONSTRAINT CK_AMENITY_MAINTENANCE_DATES CHECK (END_DATE >= START_DATE)
);
COMMENT ON TABLE AMENITY_MAINTENANCE IS 'Ngày nghỉ bảo trì (không nhận đặt chỗ)';
