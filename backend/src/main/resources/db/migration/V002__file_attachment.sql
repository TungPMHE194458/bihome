CREATE TABLE FILE_ATTACHMENT (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ORIGINAL_NAME VARCHAR2(255 CHAR) NOT NULL,
    STORED_PATH   VARCHAR2(500 CHAR) NOT NULL,
    FILE_SIZE     NUMBER(19) NOT NULL,
    CONTENT_TYPE  VARCHAR2(150 CHAR) NOT NULL,
    PURPOSE       VARCHAR2(30 CHAR) NOT NULL,
    CREATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY    VARCHAR2(100 CHAR),
    UPDATED_BY    VARCHAR2(100 CHAR),
    VERSION       NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FILE_ATTACHMENT PRIMARY KEY (ID),
    CONSTRAINT UK_FILE_ATTACHMENT_PATH UNIQUE (STORED_PATH),
    CONSTRAINT CK_FILE_ATTACHMENT_PURPOSE CHECK (PURPOSE IN (
        'BUILDING_IMAGE', 'APARTMENT_IMAGE', 'AVATAR', 'RESIDENT_AVATAR', 'AMENITY_IMAGE',
        'SERVICE_IMAGE', 'METER_IMAGE', 'DOCUMENT', 'TICKET_ATTACHMENT'))
);

COMMENT ON TABLE FILE_ATTACHMENT IS 'Metadata tệp đã tải lên; tệp vật lý nằm ở StorageService';
COMMENT ON COLUMN FILE_ATTACHMENT.ORIGINAL_NAME IS 'Tên tệp gốc do người dùng tải lên';
COMMENT ON COLUMN FILE_ATTACHMENT.STORED_PATH IS 'Đường dẫn tương đối trong kho lưu trữ: {purpose}/{yyyy}/{MM}/{uuid}.{ext}';
COMMENT ON COLUMN FILE_ATTACHMENT.FILE_SIZE IS 'Dung lượng (byte)';
COMMENT ON COLUMN FILE_ATTACHMENT.CONTENT_TYPE IS 'MIME thật, nhận diện bằng magic bytes';
COMMENT ON COLUMN FILE_ATTACHMENT.PURPOSE IS 'Mục đích sử dụng (BUILDING_IMAGE, AVATAR, DOCUMENT...)';
