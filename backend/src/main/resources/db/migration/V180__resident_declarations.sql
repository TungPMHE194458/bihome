-- App cư dân đợt 2: kê khai thành viên / xe chờ BQL duyệt, ghi nhận cư dân đã trả lời khảo sát (kể cả ẩn danh),
-- thêm loại tin hộp thư và loại thông báo cho BQL.

CREATE TABLE RESIDENT_DECLARATION (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID          NUMBER(19) NOT NULL,
    APARTMENT_ID         NUMBER(19) NOT NULL,
    CODE                 VARCHAR2(20 CHAR) NOT NULL,
    DECLARATION_TYPE     VARCHAR2(20 CHAR) NOT NULL,
    STATUS               VARCHAR2(20 CHAR) NOT NULL,
    SUBMITTED_BY_ID      NUMBER(19) NOT NULL,
    -- Thành viên
    FULL_NAME            VARCHAR2(150 CHAR),
    PHONE                VARCHAR2(20 CHAR),
    EMAIL                VARCHAR2(150 CHAR),
    GENDER               VARCHAR2(10 CHAR),
    DATE_OF_BIRTH        DATE,
    ID_TYPE              VARCHAR2(20 CHAR),
    ID_NUMBER            VARCHAR2(20 CHAR),
    RESIDENT_ROLE        VARCHAR2(30 CHAR),
    RELATIONSHIP         VARCHAR2(30 CHAR),
    MOVE_IN_DATE         DATE,
    PHOTO_FILE_ID        NUMBER(19),
    -- Xe
    CATEGORY_ID          NUMBER(19),
    VEHICLE_NAME         VARCHAR2(150 CHAR),
    PLATE_NUMBER         VARCHAR2(30 CHAR),
    VEHICLE_DESCRIPTION  VARCHAR2(1000 CHAR),
    -- Chung
    NOTE                 VARCHAR2(1000 CHAR),
    REVIEWED_AT          TIMESTAMP WITH TIME ZONE,
    REVIEWED_BY          VARCHAR2(100 CHAR),
    REJECT_REASON        VARCHAR2(500 CHAR),
    RESULT_RESIDENT_ID   NUMBER(19),
    RESULT_ASSET_ITEM_ID NUMBER(19),
    CREATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY           VARCHAR2(100 CHAR),
    UPDATED_BY           VARCHAR2(100 CHAR),
    VERSION              NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_RESIDENT_DECLARATION PRIMARY KEY (ID),
    CONSTRAINT UK_RESIDENT_DECLARATION_CODE UNIQUE (CODE),
    CONSTRAINT FK_DECLARATION_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_DECLARATION_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_DECLARATION_SUBMITTER FOREIGN KEY (SUBMITTED_BY_ID) REFERENCES RESIDENT (ID) ON DELETE CASCADE,
    CONSTRAINT FK_DECLARATION_PHOTO FOREIGN KEY (PHOTO_FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT FK_DECLARATION_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES ASSET_CATEGORY (ID) ON DELETE SET NULL,
    CONSTRAINT FK_DECLARATION_RESIDENT FOREIGN KEY (RESULT_RESIDENT_ID) REFERENCES RESIDENT (ID) ON DELETE SET NULL,
    CONSTRAINT FK_DECLARATION_ASSET FOREIGN KEY (RESULT_ASSET_ITEM_ID) REFERENCES ASSET_ITEM (ID) ON DELETE SET NULL,
    CONSTRAINT CK_DECLARATION_TYPE CHECK (DECLARATION_TYPE IN ('MEMBER', 'VEHICLE')),
    CONSTRAINT CK_DECLARATION_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT CK_DECLARATION_MEMBER CHECK (DECLARATION_TYPE <> 'MEMBER' OR (FULL_NAME IS NOT NULL AND RESIDENT_ROLE IS NOT NULL)),
    CONSTRAINT CK_DECLARATION_VEHICLE CHECK (DECLARATION_TYPE <> 'VEHICLE' OR VEHICLE_NAME IS NOT NULL),
    CONSTRAINT CK_DECLARATION_REJECTED CHECK (STATUS <> 'REJECTED' OR REJECT_REASON IS NOT NULL)
);
CREATE INDEX IDX_DECLARATION_BUILDING ON RESIDENT_DECLARATION (BUILDING_ID, STATUS, CREATED_AT);
CREATE INDEX IDX_DECLARATION_APARTMENT ON RESIDENT_DECLARATION (APARTMENT_ID);
CREATE INDEX IDX_DECLARATION_SUBMITTER ON RESIDENT_DECLARATION (SUBMITTED_BY_ID);
CREATE INDEX IDX_DECLARATION_PHOTO ON RESIDENT_DECLARATION (PHOTO_FILE_ID);
COMMENT ON TABLE RESIDENT_DECLARATION IS 'Kê khai từ app cư dân (thành viên gia đình / xe), BQL duyệt mới tạo cư dân / hạng mục';
COMMENT ON COLUMN RESIDENT_DECLARATION.STATUS IS 'PENDING chờ duyệt, APPROVED đã duyệt, REJECTED từ chối, CANCELLED cư dân huỷ';

-- Cư dân đã trả lời khảo sát qua app: chặn trả lời hai lần kể cả khảo sát ẩn danh (không nối với câu trả lời).
CREATE TABLE SURVEY_PARTICIPANT (
    SURVEY_ID   NUMBER(19) NOT NULL,
    RESIDENT_ID NUMBER(19) NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SURVEY_PARTICIPANT PRIMARY KEY (SURVEY_ID, RESIDENT_ID),
    CONSTRAINT FK_SURVEY_PARTICIPANT_SURVEY FOREIGN KEY (SURVEY_ID) REFERENCES SURVEY (ID) ON DELETE CASCADE,
    CONSTRAINT FK_SURVEY_PARTICIPANT_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_SURVEY_PARTICIPANT_RESIDENT ON SURVEY_PARTICIPANT (RESIDENT_ID);
COMMENT ON TABLE SURVEY_PARTICIPANT IS 'Cư dân đã trả lời khảo sát qua app (chỉ ghi việc đã tham gia, không nối với nội dung)';

