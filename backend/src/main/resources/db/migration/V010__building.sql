CREATE TABLE BUILDING (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODE             VARCHAR2(30 CHAR) NOT NULL,
    NAME             VARCHAR2(200 CHAR) NOT NULL,
    PROVINCE         VARCHAR2(100 CHAR) NOT NULL,
    WARD             VARCHAR2(100 CHAR) NOT NULL,
    ADDRESS_DETAIL   VARCHAR2(255 CHAR) NOT NULL,
    TYPE             VARCHAR2(30 CHAR) NOT NULL,
    FLOORS_ABOVE     NUMBER(3),
    FLOORS_BELOW     NUMBER(3),
    INVESTOR         VARCHAR2(200 CHAR),
    HOTLINE          VARCHAR2(20 CHAR),
    MANAGEMENT_EMAIL VARCHAR2(150 CHAR),
    DESCRIPTION      VARCHAR2(4000 CHAR),
    STATUS           VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY       VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY       VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION          NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_BUILDING PRIMARY KEY (ID),
    CONSTRAINT UK_BUILDING_CODE UNIQUE (CODE),
    CONSTRAINT CK_BUILDING_TYPE CHECK (TYPE IN ('BUILDING', 'COMPOUND', 'RENTAL')),
    CONSTRAINT CK_BUILDING_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_BUILDING_FLOORS CHECK (NVL(FLOORS_ABOVE, 0) >= 0 AND NVL(FLOORS_BELOW, 0) >= 0)
);
CREATE INDEX IDX_BUILDING_STATUS ON BUILDING (STATUS);
CREATE INDEX IDX_BUILDING_TYPE ON BUILDING (TYPE);
CREATE INDEX IDX_BUILDING_CREATED_AT ON BUILDING (CREATED_AT);
CREATE INDEX IDX_BUILDING_UPDATED_AT ON BUILDING (UPDATED_AT);
CREATE INDEX IDX_BUILDING_NAME_LOWER ON BUILDING (LOWER(NAME));

COMMENT ON TABLE BUILDING IS 'Tòa nhà / khu đô thị do ban quản lý vận hành';
COMMENT ON COLUMN BUILDING.CODE IS 'Mã tòa nhà: chữ in hoa không dấu, không khoảng trắng';
COMMENT ON COLUMN BUILDING.NAME IS 'Tên tòa nhà';
COMMENT ON COLUMN BUILDING.PROVINCE IS 'Tỉnh / Thành phố';
COMMENT ON COLUMN BUILDING.WARD IS 'Phường / Xã';
COMMENT ON COLUMN BUILDING.ADDRESS_DETAIL IS 'Địa chỉ chi tiết (số nhà, đường)';
COMMENT ON COLUMN BUILDING.TYPE IS 'BUILDING tòa nhà, COMPOUND khu, RENTAL cho thuê';
COMMENT ON COLUMN BUILDING.FLOORS_ABOVE IS 'Số tầng nổi';
COMMENT ON COLUMN BUILDING.FLOORS_BELOW IS 'Số tầng hầm';
COMMENT ON COLUMN BUILDING.INVESTOR IS 'Chủ đầu tư';
COMMENT ON COLUMN BUILDING.HOTLINE IS 'Hotline ban quản lý';
COMMENT ON COLUMN BUILDING.MANAGEMENT_EMAIL IS 'Email ban quản lý';
COMMENT ON COLUMN BUILDING.STATUS IS 'ACTIVE hoạt động, INACTIVE không hoạt động (ẩn khỏi bộ chọn tòa nhà)';

CREATE TABLE BUILDING_IMAGE (
    BUILDING_ID NUMBER(19) NOT NULL,
    FILE_ID     NUMBER(19) NOT NULL,
    IS_COVER    NUMBER(1) DEFAULT 0 NOT NULL,
    SORT_ORDER  NUMBER(3) NOT NULL,
    CONSTRAINT PK_BUILDING_IMAGE PRIMARY KEY (BUILDING_ID, FILE_ID),
    CONSTRAINT FK_BUILDING_IMAGE_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_BUILDING_IMAGE_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT CK_BUILDING_IMAGE_COVER CHECK (IS_COVER IN (0, 1))
);
CREATE INDEX IDX_BUILDING_IMAGE_FILE ON BUILDING_IMAGE (FILE_ID);
COMMENT ON TABLE BUILDING_IMAGE IS 'Ảnh tòa nhà, đúng một ảnh đại diện (IS_COVER = 1)';

