-- Nhắc nhở gửi cư dân và khảo sát ý kiến.

CREATE TABLE REMINDER (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID      NUMBER(19) NOT NULL,
    TITLE            VARCHAR2(200 CHAR) NOT NULL,
    CONTENT          CLOB NOT NULL,
    AUDIENCE         VARCHAR2(20 CHAR) NOT NULL,
    SCHEDULE_TYPE    VARCHAR2(20 CHAR) NOT NULL,
    SCHEDULED_AT     TIMESTAMP WITH TIME ZONE,
    MONTHLY_DAY      NUMBER(2),
    MONTHLY_TIME     VARCHAR2(5 CHAR),
    END_DATE         DATE,
    NEXT_RUN_AT      TIMESTAMP WITH TIME ZONE,
    LAST_SENT_AT     TIMESTAMP WITH TIME ZONE,
    RUN_COUNT        NUMBER(10) DEFAULT 0 NOT NULL,
    RECIPIENT_COUNT  NUMBER(10) DEFAULT 0 NOT NULL,
    STATUS           VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY       VARCHAR2(100 CHAR),
    UPDATED_BY       VARCHAR2(100 CHAR),
    VERSION          NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_REMINDER PRIMARY KEY (ID),
    CONSTRAINT FK_REMINDER_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_REMINDER_AUDIENCE CHECK (AUDIENCE IN ('ALL', 'FLOOR', 'APARTMENT', 'RESIDENT')),
    CONSTRAINT CK_REMINDER_SCHEDULE CHECK (SCHEDULE_TYPE IN ('NOW', 'ONCE', 'MONTHLY')),
    CONSTRAINT CK_REMINDER_STATUS CHECK (STATUS IN ('DRAFT', 'SCHEDULED', 'SENT', 'CANCELLED')),
    CONSTRAINT CK_REMINDER_ONCE CHECK (SCHEDULE_TYPE <> 'ONCE' OR SCHEDULED_AT IS NOT NULL),
    CONSTRAINT CK_REMINDER_MONTHLY CHECK (SCHEDULE_TYPE <> 'MONTHLY'
        OR (MONTHLY_DAY BETWEEN 1 AND 31 AND REGEXP_LIKE(MONTHLY_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$'))),
    CONSTRAINT CK_REMINDER_DUE CHECK (STATUS <> 'SCHEDULED' OR NEXT_RUN_AT IS NOT NULL)
);
CREATE INDEX IDX_REMINDER_BUILDING ON REMINDER (BUILDING_ID, STATUS);
CREATE INDEX IDX_REMINDER_DUE ON REMINDER (STATUS, NEXT_RUN_AT);
CREATE INDEX IDX_REMINDER_CREATED ON REMINDER (CREATED_AT);
COMMENT ON TABLE REMINDER IS 'Nhắc nhở gửi cư dân (gửi ngay, hẹn giờ hoặc lặp hằng tháng)';
COMMENT ON COLUMN REMINDER.CONTENT IS 'Nội dung HTML đã lọc theo danh sách thẻ cho phép';
COMMENT ON COLUMN REMINDER.AUDIENCE IS 'ALL toàn tòa, FLOOR theo tầng, APARTMENT theo căn hộ, RESIDENT cư dân cụ thể (giá trị ở REMINDER_TARGET)';
COMMENT ON COLUMN REMINDER.MONTHLY_DAY IS 'Lặp hằng tháng vào ngày này (tháng ít ngày hơn thì ngày cuối tháng)';
COMMENT ON COLUMN REMINDER.NEXT_RUN_AT IS 'Lần gửi kế tiếp; job mỗi phút gửi các nhắc nhở đến hạn';
COMMENT ON COLUMN REMINDER.RECIPIENT_COUNT IS 'Số cư dân nhận ở lần gửi gần nhất';

CREATE TABLE REMINDER_TARGET (
    REMINDER_ID  NUMBER(19) NOT NULL,
    TARGET_VALUE VARCHAR2(40 CHAR) NOT NULL,
    CONSTRAINT PK_REMINDER_TARGET PRIMARY KEY (REMINDER_ID, TARGET_VALUE),
    CONSTRAINT FK_REMINDER_TARGET_REMINDER FOREIGN KEY (REMINDER_ID) REFERENCES REMINDER (ID)
);
COMMENT ON TABLE REMINDER_TARGET IS 'Tầng / id căn hộ / id cư dân nhận nhắc nhở (theo AUDIENCE)';

CREATE TABLE REMINDER_CHANNEL (
    REMINDER_ID NUMBER(19) NOT NULL,
    CHANNEL     VARCHAR2(10 CHAR) NOT NULL,
    CONSTRAINT PK_REMINDER_CHANNEL PRIMARY KEY (REMINDER_ID, CHANNEL),
    CONSTRAINT FK_REMINDER_CHANNEL_REMINDER FOREIGN KEY (REMINDER_ID) REFERENCES REMINDER (ID),
    CONSTRAINT CK_REMINDER_CHANNEL CHECK (CHANNEL IN ('IN_APP', 'EMAIL', 'SMS'))
);

-- Kết quả gửi từng cư dân / kênh ở mỗi lần gửi (lưu tên, căn dạng chữ để không chặn xoá cư dân về sau).
CREATE TABLE REMINDER_DELIVERY (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    REMINDER_ID    NUMBER(19) NOT NULL,
    RUN_NO         NUMBER(10) NOT NULL,
    RESIDENT_ID    NUMBER(19) NOT NULL,
    RESIDENT_NAME  VARCHAR2(150 CHAR) NOT NULL,
    APARTMENT_CODE VARCHAR2(200 CHAR),
    CHANNEL        VARCHAR2(10 CHAR) NOT NULL,
    DESTINATION    VARCHAR2(150 CHAR),
    STATUS         VARCHAR2(10 CHAR) NOT NULL,
    NOTE           VARCHAR2(200 CHAR),
    SENT_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_REMINDER_DELIVERY PRIMARY KEY (ID),
    CONSTRAINT FK_REMINDER_DELIVERY_REMINDER FOREIGN KEY (REMINDER_ID) REFERENCES REMINDER (ID),
    CONSTRAINT CK_REMINDER_DELIVERY_STATUS CHECK (STATUS IN ('SENT', 'SKIPPED', 'FAILED'))
);
CREATE INDEX IDX_REMINDER_DELIVERY_REMINDER ON REMINDER_DELIVERY (REMINDER_ID, RUN_NO);
CREATE INDEX IDX_REMINDER_DELIVERY_RESIDENT ON REMINDER_DELIVERY (RESIDENT_ID);
COMMENT ON TABLE REMINDER_DELIVERY IS 'Lịch sử gửi nhắc nhở theo cư dân và kênh (local: email/SMS chỉ ghi log)';
COMMENT ON COLUMN REMINDER_DELIVERY.STATUS IS 'SENT đã gửi, SKIPPED bỏ qua (thiếu email / số điện thoại), FAILED lỗi kênh gửi';

CREATE TABLE SURVEY (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID   NUMBER(19) NOT NULL,
    TITLE         VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION   VARCHAR2(2000 CHAR),
    AUDIENCE      VARCHAR2(20 CHAR) NOT NULL,
    START_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    END_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    ANONYMOUS     NUMBER(1) DEFAULT 0 NOT NULL,
    STATUS        VARCHAR2(20 CHAR) NOT NULL,
    PUBLISHED_AT  TIMESTAMP WITH TIME ZONE,
    CLOSED_AT     TIMESTAMP WITH TIME ZONE,
    CREATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY    VARCHAR2(100 CHAR),
    UPDATED_BY    VARCHAR2(100 CHAR),
    VERSION       NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SURVEY PRIMARY KEY (ID),
    CONSTRAINT FK_SURVEY_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_SURVEY_AUDIENCE CHECK (AUDIENCE IN ('ALL', 'FLOOR', 'APARTMENT')),
    CONSTRAINT CK_SURVEY_STATUS CHECK (STATUS IN ('DRAFT', 'OPEN', 'CLOSED')),
    CONSTRAINT CK_SURVEY_ANONYMOUS CHECK (ANONYMOUS IN (0, 1)),
    CONSTRAINT CK_SURVEY_PERIOD CHECK (END_AT > START_AT)
);
CREATE INDEX IDX_SURVEY_BUILDING ON SURVEY (BUILDING_ID, STATUS);
CREATE INDEX IDX_SURVEY_END ON SURVEY (STATUS, END_AT);
CREATE INDEX IDX_SURVEY_CREATED ON SURVEY (CREATED_AT);
COMMENT ON TABLE SURVEY IS 'Khảo sát ý kiến cư dân';
COMMENT ON COLUMN SURVEY.ANONYMOUS IS '1 = không lưu cư dân / căn hộ của phản hồi';
COMMENT ON COLUMN SURVEY.STATUS IS 'DRAFT nháp, OPEN đang mở (nhận phản hồi trong START_AT–END_AT), CLOSED đã đóng';

CREATE TABLE SURVEY_TARGET (
    SURVEY_ID    NUMBER(19) NOT NULL,
    TARGET_VALUE VARCHAR2(40 CHAR) NOT NULL,
    CONSTRAINT PK_SURVEY_TARGET PRIMARY KEY (SURVEY_ID, TARGET_VALUE),
    CONSTRAINT FK_SURVEY_TARGET_SURVEY FOREIGN KEY (SURVEY_ID) REFERENCES SURVEY (ID)
);

CREATE TABLE SURVEY_QUESTION (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    SURVEY_ID  NUMBER(19) NOT NULL,
    POSITION   NUMBER(5) NOT NULL,
    TYPE_CODE  VARCHAR2(20 CHAR) NOT NULL,
    CONTENT    VARCHAR2(500 CHAR) NOT NULL,
    REQUIRED   NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_SURVEY_QUESTION PRIMARY KEY (ID),
    CONSTRAINT FK_SURVEY_QUESTION_SURVEY FOREIGN KEY (SURVEY_ID) REFERENCES SURVEY (ID),
    CONSTRAINT CK_SURVEY_QUESTION_TYPE CHECK (TYPE_CODE IN ('SINGLE', 'MULTIPLE', 'TEXT', 'RATING')),
    CONSTRAINT CK_SURVEY_QUESTION_REQUIRED CHECK (REQUIRED IN (0, 1))
);
CREATE INDEX IDX_SURVEY_QUESTION_SURVEY ON SURVEY_QUESTION (SURVEY_ID, POSITION);

CREATE TABLE SURVEY_OPTION (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    QUESTION_ID NUMBER(19) NOT NULL,
    POSITION    NUMBER(5) NOT NULL,
    LABEL       VARCHAR2(200 CHAR) NOT NULL,
    CONSTRAINT PK_SURVEY_OPTION PRIMARY KEY (ID),
    CONSTRAINT FK_SURVEY_OPTION_QUESTION FOREIGN KEY (QUESTION_ID) REFERENCES SURVEY_QUESTION (ID)
);
CREATE INDEX IDX_SURVEY_OPTION_QUESTION ON SURVEY_OPTION (QUESTION_ID, POSITION);

CREATE TABLE SURVEY_RESPONSE (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    SURVEY_ID    NUMBER(19) NOT NULL,
    APARTMENT_ID NUMBER(19),
    RESIDENT_ID  NUMBER(19),
    SUBMITTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(100 CHAR),
    UPDATED_BY   VARCHAR2(100 CHAR),
    VERSION      NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SURVEY_RESPONSE PRIMARY KEY (ID),
    CONSTRAINT FK_SURVEY_RESPONSE_SURVEY FOREIGN KEY (SURVEY_ID) REFERENCES SURVEY (ID),
    CONSTRAINT FK_SURVEY_RESPONSE_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_SURVEY_RESPONSE_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID)
);
CREATE INDEX IDX_SURVEY_RESPONSE_SURVEY ON SURVEY_RESPONSE (SURVEY_ID, SUBMITTED_AT);
CREATE INDEX IDX_SURVEY_RESPONSE_APARTMENT ON SURVEY_RESPONSE (APARTMENT_ID);
-- Mỗi cư dân phản hồi một lần (phản hồi ẩn danh không lưu cư dân).
CREATE UNIQUE INDEX UK_SURVEY_RESPONSE_RESIDENT ON SURVEY_RESPONSE (
    CASE WHEN RESIDENT_ID IS NOT NULL THEN SURVEY_ID END, CASE WHEN RESIDENT_ID IS NOT NULL THEN RESIDENT_ID END);
COMMENT ON TABLE SURVEY_RESPONSE IS 'Một lượt trả lời khảo sát (BQL nhập hộ hoặc cư dân gửi qua app)';

CREATE TABLE SURVEY_ANSWER (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RESPONSE_ID NUMBER(19) NOT NULL,
    QUESTION_ID NUMBER(19) NOT NULL,
    OPTION_ID   NUMBER(19),
    TEXT_VALUE  VARCHAR2(2000 CHAR),
    RATING      NUMBER(1),
    CONSTRAINT PK_SURVEY_ANSWER PRIMARY KEY (ID),
    CONSTRAINT FK_SURVEY_ANSWER_RESPONSE FOREIGN KEY (RESPONSE_ID) REFERENCES SURVEY_RESPONSE (ID),
    CONSTRAINT FK_SURVEY_ANSWER_QUESTION FOREIGN KEY (QUESTION_ID) REFERENCES SURVEY_QUESTION (ID),
    CONSTRAINT FK_SURVEY_ANSWER_OPTION FOREIGN KEY (OPTION_ID) REFERENCES SURVEY_OPTION (ID),
    CONSTRAINT CK_SURVEY_ANSWER_RATING CHECK (RATING IS NULL OR RATING BETWEEN 1 AND 5)
);
CREATE INDEX IDX_SURVEY_ANSWER_RESPONSE ON SURVEY_ANSWER (RESPONSE_ID);
CREATE INDEX IDX_SURVEY_ANSWER_QUESTION ON SURVEY_ANSWER (QUESTION_ID);
CREATE INDEX IDX_SURVEY_ANSWER_OPTION ON SURVEY_ANSWER (OPTION_ID);
COMMENT ON TABLE SURVEY_ANSWER IS 'Câu trả lời: lựa chọn (mỗi lựa chọn một dòng), văn bản hoặc số sao';
