-- Đăng ký tiện ích, đơn dịch vụ, lượt dùng voucher và lịch sử giao dịch.

-- Bộ đếm mã theo ngày dùng chung (DK-yyMMdd-001, DV-..., GD-...): UPDATE khoá dòng + INSERT bỏ qua trùng khoá.
CREATE TABLE CODE_COUNTER (
    PREFIX    VARCHAR2(10 CHAR) NOT NULL,
    CODE_DATE VARCHAR2(6 CHAR) NOT NULL,
    LAST_NO   NUMBER(10) NOT NULL,
    CONSTRAINT PK_CODE_COUNTER PRIMARY KEY (PREFIX, CODE_DATE)
);
COMMENT ON TABLE CODE_COUNTER IS 'Số thứ tự cuối cùng theo tiền tố mã và ngày (yyMMdd)';

CREATE TABLE AMENITY_BOOKING (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID    NUMBER(19) NOT NULL,
    CODE           VARCHAR2(20 CHAR) NOT NULL,
    AMENITY_ID     NUMBER(19) NOT NULL,
    APARTMENT_ID   NUMBER(19) NOT NULL,
    RESIDENT_ID    NUMBER(19),
    BOOKING_DATE   DATE NOT NULL,
    START_TIME     VARCHAR2(5 CHAR) NOT NULL,
    END_TIME       VARCHAR2(5 CHAR) NOT NULL,
    PEOPLE_COUNT   NUMBER(5) NOT NULL,
    UNIT_PRICE     NUMBER(15) DEFAULT 0 NOT NULL,
    PRICE_UNIT     VARCHAR2(20 CHAR),
    FEE            NUMBER(15) DEFAULT 0 NOT NULL,
    VOUCHER_ID     NUMBER(19),
    DISCOUNT       NUMBER(15) DEFAULT 0 NOT NULL,
    TOTAL          NUMBER(15) DEFAULT 0 NOT NULL,
    STATUS         VARCHAR2(20 CHAR) NOT NULL,
    NOTE           VARCHAR2(500 CHAR),
    REJECT_REASON  VARCHAR2(500 CHAR),
    CANCEL_REASON  VARCHAR2(500 CHAR),
    DECIDED_AT     TIMESTAMP WITH TIME ZONE,
    DECIDED_BY     VARCHAR2(100 CHAR),
    CANCELLED_AT   TIMESTAMP WITH TIME ZONE,
    COMPLETED_AT   TIMESTAMP WITH TIME ZONE,
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(100 CHAR),
    UPDATED_BY     VARCHAR2(100 CHAR),
    VERSION        NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_AMENITY_BOOKING PRIMARY KEY (ID),
    CONSTRAINT UK_AMENITY_BOOKING_CODE UNIQUE (CODE),
    CONSTRAINT FK_AMENITY_BOOKING_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_AMENITY_BOOKING_AMENITY FOREIGN KEY (AMENITY_ID) REFERENCES AMENITY (ID),
    CONSTRAINT FK_AMENITY_BOOKING_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_AMENITY_BOOKING_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID),
    CONSTRAINT FK_AMENITY_BOOKING_VOUCHER FOREIGN KEY (VOUCHER_ID) REFERENCES VOUCHER (ID),
    CONSTRAINT CK_AMENITY_BOOKING_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT CK_AMENITY_BOOKING_TIME CHECK (START_TIME < END_TIME),
    CONSTRAINT CK_AMENITY_BOOKING_PEOPLE CHECK (PEOPLE_COUNT > 0),
    CONSTRAINT CK_AMENITY_BOOKING_MONEY CHECK (FEE >= 0 AND DISCOUNT >= 0 AND DISCOUNT <= FEE AND TOTAL = FEE - DISCOUNT),
    CONSTRAINT CK_AMENITY_BOOKING_UNIT CHECK (PRICE_UNIT IS NULL OR PRICE_UNIT IN ('PER_BOOKING', 'PER_PERSON'))
);
CREATE INDEX IDX_AMENITY_BOOKING_SLOT ON AMENITY_BOOKING (AMENITY_ID, BOOKING_DATE, START_TIME);
CREATE INDEX IDX_AMENITY_BOOKING_APARTMENT ON AMENITY_BOOKING (APARTMENT_ID, BOOKING_DATE);
CREATE INDEX IDX_AMENITY_BOOKING_BUILDING ON AMENITY_BOOKING (BUILDING_ID, BOOKING_DATE);
CREATE INDEX IDX_AMENITY_BOOKING_RESIDENT ON AMENITY_BOOKING (RESIDENT_ID);
CREATE INDEX IDX_AMENITY_BOOKING_VOUCHER ON AMENITY_BOOKING (VOUCHER_ID);
CREATE INDEX IDX_AMENITY_BOOKING_STATUS ON AMENITY_BOOKING (STATUS);
CREATE INDEX IDX_AMENITY_BOOKING_CREATED ON AMENITY_BOOKING (CREATED_AT);
COMMENT ON TABLE AMENITY_BOOKING IS 'Đăng ký sử dụng tiện ích theo khung giờ';
COMMENT ON COLUMN AMENITY_BOOKING.CODE IS 'Mã đăng ký DK-yyMMdd-xxx';
COMMENT ON COLUMN AMENITY_BOOKING.START_TIME IS 'Khung giờ bắt đầu HH:mm (theo cấu hình tiện ích lúc đặt)';
COMMENT ON COLUMN AMENITY_BOOKING.FEE IS 'Phí trước giảm giá (VND) = đơn giá × (số người nếu tính theo người)';
COMMENT ON COLUMN AMENITY_BOOKING.TOTAL IS 'Thành tiền = phí - giảm giá voucher';
COMMENT ON COLUMN AMENITY_BOOKING.DECIDED_BY IS 'Người duyệt / từ chối';

CREATE TABLE SERVICE_ORDER (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID    NUMBER(19) NOT NULL,
    CODE           VARCHAR2(20 CHAR) NOT NULL,
    SERVICE_ID     NUMBER(19) NOT NULL,
    APARTMENT_ID   NUMBER(19) NOT NULL,
    RESIDENT_ID    NUMBER(19),
    QUANTITY       NUMBER(10, 2) NOT NULL,
    UNIT_PRICE     NUMBER(15) NOT NULL,
    UNIT           VARCHAR2(30 CHAR) NOT NULL,
    AMOUNT         NUMBER(15) NOT NULL,
    VOUCHER_ID     NUMBER(19),
    DISCOUNT       NUMBER(15) DEFAULT 0 NOT NULL,
    TOTAL          NUMBER(15) NOT NULL,
    SCHEDULED_AT   TIMESTAMP WITH TIME ZONE,
    STATUS         VARCHAR2(20 CHAR) NOT NULL,
    NOTE           VARCHAR2(500 CHAR),
    CANCEL_REASON  VARCHAR2(500 CHAR),
    COMPLETED_AT   TIMESTAMP WITH TIME ZONE,
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(100 CHAR),
    UPDATED_BY     VARCHAR2(100 CHAR),
    VERSION        NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SERVICE_ORDER PRIMARY KEY (ID),
    CONSTRAINT UK_SERVICE_ORDER_CODE UNIQUE (CODE),
    CONSTRAINT FK_SERVICE_ORDER_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_SERVICE_ORDER_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES SERVICE (ID),
    CONSTRAINT FK_SERVICE_ORDER_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_SERVICE_ORDER_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID),
    CONSTRAINT FK_SERVICE_ORDER_VOUCHER FOREIGN KEY (VOUCHER_ID) REFERENCES VOUCHER (ID),
    CONSTRAINT CK_SERVICE_ORDER_STATUS CHECK (STATUS IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT CK_SERVICE_ORDER_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CK_SERVICE_ORDER_MONEY CHECK (DISCOUNT >= 0 AND DISCOUNT <= AMOUNT AND TOTAL = AMOUNT - DISCOUNT)
);
CREATE INDEX IDX_SERVICE_ORDER_BUILDING ON SERVICE_ORDER (BUILDING_ID, CREATED_AT);
CREATE INDEX IDX_SERVICE_ORDER_SERVICE ON SERVICE_ORDER (SERVICE_ID);
CREATE INDEX IDX_SERVICE_ORDER_APARTMENT ON SERVICE_ORDER (APARTMENT_ID);
CREATE INDEX IDX_SERVICE_ORDER_RESIDENT ON SERVICE_ORDER (RESIDENT_ID);
CREATE INDEX IDX_SERVICE_ORDER_VOUCHER ON SERVICE_ORDER (VOUCHER_ID);
CREATE INDEX IDX_SERVICE_ORDER_STATUS ON SERVICE_ORDER (STATUS);
COMMENT ON TABLE SERVICE_ORDER IS 'Đơn dịch vụ của căn hộ (số lượng × đơn giá) → sinh giao dịch';
COMMENT ON COLUMN SERVICE_ORDER.UNIT_PRICE IS 'Đơn giá dịch vụ tại thời điểm đặt';
COMMENT ON COLUMN SERVICE_ORDER.SCHEDULED_AT IS 'Thời gian hẹn thực hiện';

-- Lượt dùng voucher: đếm giới hạn mỗi căn; huỷ sớm thì xoá lượt và trả lại số lượng.
CREATE TABLE VOUCHER_USAGE (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    VOUCHER_ID   NUMBER(19) NOT NULL,
    APARTMENT_ID NUMBER(19) NOT NULL,
    SOURCE_TYPE  VARCHAR2(20 CHAR) NOT NULL,
    SOURCE_ID    NUMBER(19) NOT NULL,
    DISCOUNT     NUMBER(15) NOT NULL,
    USED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_VOUCHER_USAGE PRIMARY KEY (ID),
    CONSTRAINT UK_VOUCHER_USAGE_SOURCE UNIQUE (SOURCE_TYPE, SOURCE_ID),
    CONSTRAINT FK_VOUCHER_USAGE_VOUCHER FOREIGN KEY (VOUCHER_ID) REFERENCES VOUCHER (ID),
    CONSTRAINT FK_VOUCHER_USAGE_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT CK_VOUCHER_USAGE_SOURCE CHECK (SOURCE_TYPE IN ('AMENITY_BOOKING', 'SERVICE_ORDER'))
);
CREATE INDEX IDX_VOUCHER_USAGE_VOUCHER ON VOUCHER_USAGE (VOUCHER_ID, APARTMENT_ID);
CREATE INDEX IDX_VOUCHER_USAGE_APARTMENT ON VOUCHER_USAGE (APARTMENT_ID);
COMMENT ON TABLE VOUCHER_USAGE IS 'Lượt dùng voucher của căn hộ (đăng ký tiện ích / đơn dịch vụ)';

-- Giao dịch phát sinh từ đăng ký tiện ích, đơn dịch vụ, thẻ từ, thông báo phí (chỉ đọc ở màn hình Lịch sử giao dịch).
CREATE TABLE FINANCIAL_TRANSACTION (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID   NUMBER(19) NOT NULL,
    CODE          VARCHAR2(20 CHAR) NOT NULL,
    SOURCE_TYPE   VARCHAR2(20 CHAR) NOT NULL,
    SOURCE_ID     NUMBER(19) NOT NULL,
    SOURCE_CODE   VARCHAR2(40 CHAR) NOT NULL,
    APARTMENT_ID  NUMBER(19),
    RESIDENT_ID   NUMBER(19),
    AMOUNT        NUMBER(15) NOT NULL,
    METHOD        VARCHAR2(20 CHAR),
    STATUS        VARCHAR2(20 CHAR) NOT NULL,
    DESCRIPTION   VARCHAR2(500 CHAR),
    PAID_AT       TIMESTAMP WITH TIME ZONE,
    CREATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY    VARCHAR2(100 CHAR),
    UPDATED_BY    VARCHAR2(100 CHAR),
    VERSION       NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FINANCIAL_TRANSACTION PRIMARY KEY (ID),
    CONSTRAINT UK_FINANCIAL_TRANSACTION_CODE UNIQUE (CODE),
    CONSTRAINT UK_FINANCIAL_TRANSACTION_SOURCE UNIQUE (SOURCE_TYPE, SOURCE_ID),
    CONSTRAINT FK_FIN_TRANSACTION_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_FIN_TRANSACTION_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_FIN_TRANSACTION_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID),
    CONSTRAINT CK_FIN_TRANSACTION_SOURCE CHECK (SOURCE_TYPE IN ('AMENITY_BOOKING', 'SERVICE_ORDER', 'ACCESS_CARD', 'FEE_NOTICE')),
    CONSTRAINT CK_FIN_TRANSACTION_METHOD CHECK (METHOD IS NULL OR METHOD IN ('CASH', 'BANK_TRANSFER', 'VIETQR', 'CARD')),
    CONSTRAINT CK_FIN_TRANSACTION_STATUS CHECK (STATUS IN ('PENDING', 'PAID', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT CK_FIN_TRANSACTION_PAID CHECK (STATUS NOT IN ('PAID', 'REFUNDED') OR (PAID_AT IS NOT NULL AND METHOD IS NOT NULL)),
    CONSTRAINT CK_FIN_TRANSACTION_AMOUNT CHECK (AMOUNT > 0)
);
CREATE INDEX IDX_FIN_TRANSACTION_BUILDING ON FINANCIAL_TRANSACTION (BUILDING_ID, CREATED_AT);
CREATE INDEX IDX_FIN_TRANSACTION_APARTMENT ON FINANCIAL_TRANSACTION (APARTMENT_ID, STATUS);
CREATE INDEX IDX_FIN_TRANSACTION_RESIDENT ON FINANCIAL_TRANSACTION (RESIDENT_ID);
CREATE INDEX IDX_FIN_TRANSACTION_STATUS ON FINANCIAL_TRANSACTION (STATUS);
COMMENT ON TABLE FINANCIAL_TRANSACTION IS 'Giao dịch phát sinh (tiện ích, dịch vụ, thẻ từ, thông báo phí)';
COMMENT ON COLUMN FINANCIAL_TRANSACTION.SOURCE_CODE IS 'Mã tham chiếu: mã đăng ký / đơn dịch vụ / mã thẻ / mã thông báo phí';
COMMENT ON COLUMN FINANCIAL_TRANSACTION.STATUS IS 'PENDING chưa thanh toán (cộng vào thông báo phí kỳ sau), PAID, CANCELLED, REFUNDED';

