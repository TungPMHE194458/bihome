CREATE TABLE ASSET_CATEGORY (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID NUMBER(19) NOT NULL,
    NAME        VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    UNIT        VARCHAR2(30 CHAR) NOT NULL,
    STATUS      VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION     NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ASSET_CATEGORY PRIMARY KEY (ID),
    CONSTRAINT FK_ASSET_CATEGORY_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_ASSET_CATEGORY_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);
-- Tên danh mục duy nhất trong tòa, không phân biệt hoa thường (index dẫn đầu bằng BUILDING_ID, đủ cho FK).
CREATE UNIQUE INDEX UK_ASSET_CATEGORY_NAME ON ASSET_CATEGORY (BUILDING_ID, LOWER(NAME));
CREATE INDEX IDX_ASSET_CATEGORY_STATUS ON ASSET_CATEGORY (STATUS);

COMMENT ON TABLE ASSET_CATEGORY IS 'Danh mục tài sản kê khai (Ô tô, Xe máy, Xe đạp, Xe điện...) theo tòa nhà';
COMMENT ON COLUMN ASSET_CATEGORY.NAME IS 'Tên danh mục, duy nhất trong tòa';
COMMENT ON COLUMN ASSET_CATEGORY.UNIT IS 'Đơn vị mặc định (chiếc, cái, bộ...)';

CREATE TABLE ASSET_ITEM (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID  NUMBER(19) NOT NULL,
    APARTMENT_ID NUMBER(19) NOT NULL,
    CATEGORY_ID  NUMBER(19) NOT NULL,
    NAME         VARCHAR2(150 CHAR) NOT NULL,
    PLATE_NUMBER VARCHAR2(30 CHAR),
    DESCRIPTION  VARCHAR2(1000 CHAR),
    UNIT         VARCHAR2(30 CHAR) NOT NULL,
    ENTRY_DATE   DATE NOT NULL,
    EXIT_DATE    DATE,
    STATUS       VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY   VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION      NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ASSET_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_ASSET_ITEM_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_ASSET_ITEM_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_ASSET_ITEM_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES ASSET_CATEGORY (ID),
    CONSTRAINT CK_ASSET_ITEM_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_ASSET_ITEM_DATES CHECK (EXIT_DATE IS NULL OR EXIT_DATE >= ENTRY_DATE)
);
CREATE INDEX IDX_ASSET_ITEM_BUILDING_STATUS ON ASSET_ITEM (BUILDING_ID, STATUS);
CREATE INDEX IDX_ASSET_ITEM_APARTMENT ON ASSET_ITEM (APARTMENT_ID);
CREATE INDEX IDX_ASSET_ITEM_CATEGORY ON ASSET_ITEM (CATEGORY_ID);
CREATE INDEX IDX_ASSET_ITEM_ENTRY_DATE ON ASSET_ITEM (ENTRY_DATE);
CREATE INDEX IDX_ASSET_ITEM_EXIT_DATE ON ASSET_ITEM (EXIT_DATE);
CREATE INDEX IDX_ASSET_ITEM_CREATED_AT ON ASSET_ITEM (CREATED_AT);
-- Biển số duy nhất trong tòa chỉ với hạng mục đang hoạt động: dòng không thoả điều kiện có khoá NULL nên không bị index.
CREATE UNIQUE INDEX UK_ASSET_ITEM_ACTIVE_PLATE ON ASSET_ITEM (
    CASE WHEN STATUS = 'ACTIVE' AND PLATE_NUMBER IS NOT NULL THEN BUILDING_ID END,
    CASE WHEN STATUS = 'ACTIVE' AND PLATE_NUMBER IS NOT NULL THEN PLATE_NUMBER END
);

COMMENT ON TABLE ASSET_ITEM IS 'Hạng mục kê khai của căn hộ (xe...), dùng tính phí gửi xe';
COMMENT ON COLUMN ASSET_ITEM.NAME IS 'Tên hạng mục, vd Honda Vision đỏ';
COMMENT ON COLUMN ASSET_ITEM.PLATE_NUMBER IS 'Số hiệu / biển số đã chuẩn hoá (in hoa, bỏ khoảng trắng thừa)';
COMMENT ON COLUMN ASSET_ITEM.UNIT IS 'Đơn vị (mặc định theo danh mục)';
COMMENT ON COLUMN ASSET_ITEM.ENTRY_DATE IS 'Ngày vào';
COMMENT ON COLUMN ASSET_ITEM.EXIT_DATE IS 'Ngày ra; ngày ra ≤ hôm nay thì hạng mục tự chuyển Không hoạt động';
