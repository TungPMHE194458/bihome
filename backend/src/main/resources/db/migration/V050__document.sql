CREATE TABLE DOCUMENT_CATEGORY (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME        VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    COLOR       VARCHAR2(7 CHAR) DEFAULT '#16A34A' NOT NULL,
    STATUS      VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION     NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DOCUMENT_CATEGORY PRIMARY KEY (ID),
    CONSTRAINT CK_DOCUMENT_CATEGORY_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_DOCUMENT_CATEGORY_COLOR CHECK (REGEXP_LIKE(COLOR, '^#[0-9A-Fa-f]{6}$'))
);
-- Danh mục dùng chung cho mọi tòa; tên duy nhất không phân biệt hoa thường.
CREATE UNIQUE INDEX UK_DOCUMENT_CATEGORY_NAME ON DOCUMENT_CATEGORY (LOWER(NAME));
CREATE INDEX IDX_DOCUMENT_CATEGORY_STATUS ON DOCUMENT_CATEGORY (STATUS);

COMMENT ON TABLE DOCUMENT_CATEGORY IS 'Danh mục tài liệu (Nội quy, Hợp đồng mẫu, Biểu mẫu...), dùng chung cho mọi tòa';
COMMENT ON COLUMN DOCUMENT_CATEGORY.COLOR IS 'Màu chip hiển thị, dạng #RRGGBB';

