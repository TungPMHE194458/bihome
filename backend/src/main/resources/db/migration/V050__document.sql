CREATE TABLE DOCUMENT (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID     NUMBER(19) NOT NULL,
    CODE            VARCHAR2(30 CHAR) NOT NULL,
    NAME            VARCHAR2(255 CHAR) NOT NULL,
    DESCRIPTION     VARCHAR2(2000 CHAR),
    CATEGORY_ID     NUMBER(19) NOT NULL,
    AUDIENCE        VARCHAR2(30 CHAR) DEFAULT 'ALL_RESIDENTS' NOT NULL,
    FILE_ID         NUMBER(19) NOT NULL,
    FILE_VERSION_NO NUMBER(5) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY      VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY      VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION         NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DOCUMENT PRIMARY KEY (ID),
    CONSTRAINT FK_DOCUMENT_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_DOCUMENT_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES DOCUMENT_CATEGORY (ID),
    CONSTRAINT FK_DOCUMENT_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT UK_DOCUMENT_FILE UNIQUE (FILE_ID),
    CONSTRAINT CK_DOCUMENT_AUDIENCE CHECK (AUDIENCE IN ('ALL_RESIDENTS', 'OWNERS', 'TENANTS', 'MANAGEMENT')),
    CONSTRAINT CK_DOCUMENT_FILE_VERSION CHECK (FILE_VERSION_NO >= 1)
);
CREATE UNIQUE INDEX UK_DOCUMENT_CODE ON DOCUMENT (BUILDING_ID, CODE);
CREATE INDEX IDX_DOCUMENT_CATEGORY ON DOCUMENT (CATEGORY_ID);
CREATE INDEX IDX_DOCUMENT_AUDIENCE ON DOCUMENT (BUILDING_ID, AUDIENCE);
CREATE INDEX IDX_DOCUMENT_CREATED_AT ON DOCUMENT (CREATED_AT);
CREATE INDEX IDX_DOCUMENT_UPDATED_AT ON DOCUMENT (UPDATED_AT);

COMMENT ON TABLE DOCUMENT IS 'Tài liệu của tòa nhà; tệp hiện tại ở FILE_ID, tệp cũ ở DOCUMENT_FILE_VERSION';
COMMENT ON COLUMN DOCUMENT.CODE IS 'Mã tài liệu, duy nhất trong tòa; tự sinh số tăng dần nếu bỏ trống';
COMMENT ON COLUMN DOCUMENT.AUDIENCE IS 'Đối tượng: ALL_RESIDENTS | OWNERS | TENANTS | MANAGEMENT (nội bộ BQL)';
COMMENT ON COLUMN DOCUMENT.FILE_VERSION_NO IS 'Số phiên bản của tệp hiện tại, tăng mỗi lần thay tệp';

CREATE TABLE DOCUMENT_TAG (
    DOCUMENT_ID NUMBER(19) NOT NULL,
    TAG         VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT PK_DOCUMENT_TAG PRIMARY KEY (DOCUMENT_ID, TAG),
    CONSTRAINT FK_DOCUMENT_TAG_DOCUMENT FOREIGN KEY (DOCUMENT_ID) REFERENCES DOCUMENT (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_DOCUMENT_TAG_TAG ON DOCUMENT_TAG (LOWER(TAG));

COMMENT ON TABLE DOCUMENT_TAG IS 'Thẻ của tài liệu (nhiều thẻ / tài liệu)';

CREATE TABLE DOCUMENT_FILE_VERSION (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    DOCUMENT_ID NUMBER(19) NOT NULL,
    VERSION_NO  NUMBER(5) NOT NULL,
    FILE_ID     NUMBER(19) NOT NULL,
    NOTE        VARCHAR2(500 CHAR),
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY  VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION     NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DOCUMENT_FILE_VERSION PRIMARY KEY (ID),
    CONSTRAINT FK_DOCUMENT_FILE_VERSION_DOC FOREIGN KEY (DOCUMENT_ID) REFERENCES DOCUMENT (ID),
    CONSTRAINT FK_DOCUMENT_FILE_VERSION_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT UK_DOCUMENT_FILE_VERSION_NO UNIQUE (DOCUMENT_ID, VERSION_NO),
    CONSTRAINT UK_DOCUMENT_FILE_VERSION_FILE UNIQUE (FILE_ID)
);

COMMENT ON TABLE DOCUMENT_FILE_VERSION IS 'Phiên bản cũ của tệp tài liệu, lưu lại mỗi khi thay tệp';
COMMENT ON COLUMN DOCUMENT_FILE_VERSION.VERSION_NO IS 'Số phiên bản của tệp cũ này';
COMMENT ON COLUMN DOCUMENT_FILE_VERSION.NOTE IS 'Ghi chú khi thay tệp (lý do / nội dung thay đổi)';
