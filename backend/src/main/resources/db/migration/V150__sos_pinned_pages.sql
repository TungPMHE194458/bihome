-- Cảnh báo khẩn cấp (SOS) và trang ghim (Truy cập nhanh) theo người dùng.

CREATE TABLE SOS_ALERT (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID     NUMBER(19) NOT NULL,
    CODE            VARCHAR2(20 CHAR) NOT NULL,
    ALERT_TYPE      VARCHAR2(20 CHAR) NOT NULL,
    SOURCE          VARCHAR2(10 CHAR) NOT NULL,
    APARTMENT_ID    NUMBER(19),
    REPORTER_NAME   VARCHAR2(150 CHAR),
    REPORTER_PHONE  VARCHAR2(20 CHAR),
    LOCATION        VARCHAR2(200 CHAR),
    DESCRIPTION     VARCHAR2(1000 CHAR),
    STATUS          VARCHAR2(20 CHAR) NOT NULL,
    ACKNOWLEDGED_AT TIMESTAMP WITH TIME ZONE,
    ACKNOWLEDGED_BY VARCHAR2(100 CHAR),
    RESOLVED_AT     TIMESTAMP WITH TIME ZONE,
    RESOLVED_BY     VARCHAR2(100 CHAR),
    RESOLUTION_NOTE VARCHAR2(1000 CHAR),
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY      VARCHAR2(100 CHAR),
    UPDATED_BY      VARCHAR2(100 CHAR),
    VERSION         NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SOS_ALERT PRIMARY KEY (ID),
    CONSTRAINT FK_SOS_ALERT_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_SOS_ALERT_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT UK_SOS_ALERT_CODE UNIQUE (CODE),
    CONSTRAINT CK_SOS_ALERT_TYPE CHECK (ALERT_TYPE IN ('FIRE', 'MEDICAL', 'SECURITY', 'ELEVATOR', 'OTHER')),
    CONSTRAINT CK_SOS_ALERT_SOURCE CHECK (SOURCE IN ('MANUAL', 'APP')),
    CONSTRAINT CK_SOS_ALERT_STATUS CHECK (STATUS IN ('NEW', 'ACKNOWLEDGED', 'RESOLVED', 'FALSE_ALARM')),
    CONSTRAINT CK_SOS_ALERT_ACK CHECK (STATUS = 'NEW' OR ACKNOWLEDGED_AT IS NOT NULL),
    CONSTRAINT CK_SOS_ALERT_RESOLVED CHECK (STATUS IN ('NEW', 'ACKNOWLEDGED')
        OR (RESOLVED_AT IS NOT NULL AND RESOLUTION_NOTE IS NOT NULL))
);
CREATE INDEX IDX_SOS_ALERT_BUILDING ON SOS_ALERT (BUILDING_ID, STATUS, CREATED_AT);
CREATE INDEX IDX_SOS_ALERT_APARTMENT ON SOS_ALERT (APARTMENT_ID);
CREATE INDEX IDX_SOS_ALERT_CREATED ON SOS_ALERT (CREATED_AT);
COMMENT ON TABLE SOS_ALERT IS 'Cảnh báo khẩn cấp từ cư dân (app) hoặc BQL tạo tay';
COMMENT ON COLUMN SOS_ALERT.STATUS IS 'NEW mới, ACKNOWLEDGED đã tiếp nhận, RESOLVED đã xử lý, FALSE_ALARM báo nhầm';

CREATE TABLE USER_PINNED_PAGE (
    USER_ID NUMBER(19) NOT NULL,
    LINE_NO NUMBER(3) NOT NULL,
    PATH    VARCHAR2(300 CHAR) NOT NULL,
    TITLE   VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT PK_USER_PINNED_PAGE PRIMARY KEY (USER_ID, LINE_NO),
    CONSTRAINT FK_USER_PINNED_PAGE_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (ID) ON DELETE CASCADE
);
COMMENT ON TABLE USER_PINNED_PAGE IS 'Trang người dùng ghim vào "Truy cập nhanh" (theo thứ tự)';

