-- Cấu hình chung của hệ thống (một dòng duy nhất, ID = 1).
CREATE TABLE SYSTEM_SETTING (
    ID                NUMBER(1) DEFAULT 1 NOT NULL,
    COMPANY_NAME      VARCHAR2(200 CHAR),
    TAX_CODE          VARCHAR2(20 CHAR),
    ADDRESS           VARCHAR2(300 CHAR),
    HOTLINE           VARCHAR2(20 CHAR),
    EMAIL             VARCHAR2(150 CHAR),
    WEBSITE           VARCHAR2(150 CHAR),
    DOCUMENT_FOOTER   VARCHAR2(300 CHAR),
    MAX_FAILED_LOGINS NUMBER(2) DEFAULT 5 NOT NULL,
    LOCK_MINUTES      NUMBER(4) DEFAULT 15 NOT NULL,
    FEE_NOTICE_EMAIL  NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY        VARCHAR2(100 CHAR),
    UPDATED_BY        VARCHAR2(100 CHAR),
    VERSION           NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SYSTEM_SETTING PRIMARY KEY (ID),
    CONSTRAINT CK_SYSTEM_SETTING_SINGLE CHECK (ID = 1),
    CONSTRAINT CK_SYSTEM_SETTING_LOGINS CHECK (MAX_FAILED_LOGINS BETWEEN 3 AND 20),
    CONSTRAINT CK_SYSTEM_SETTING_LOCK CHECK (LOCK_MINUTES BETWEEN 1 AND 1440),
    CONSTRAINT CK_SYSTEM_SETTING_FEE_EMAIL CHECK (FEE_NOTICE_EMAIL IN (0, 1))
);
COMMENT ON TABLE SYSTEM_SETTING IS 'Cấu hình chung (một dòng): thông tin đơn vị quản lý in trên PDF, chính sách đăng nhập, gửi email thông báo phí';
COMMENT ON COLUMN SYSTEM_SETTING.DOCUMENT_FOOTER IS 'Dòng chân trang thông báo phí / phiếu thu (bỏ trống = câu cảm ơn mặc định)';

INSERT INTO SYSTEM_SETTING (ID, CREATED_BY, UPDATED_BY) VALUES (1, 'system', 'system');
