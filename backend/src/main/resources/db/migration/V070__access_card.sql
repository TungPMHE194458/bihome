CREATE TABLE ACCESS_CARD (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID    NUMBER(19) NOT NULL,
    CARD_NO        VARCHAR2(30 CHAR) NOT NULL,
    CARD_TYPE      VARCHAR2(20 CHAR) NOT NULL,
    APARTMENT_ID   NUMBER(19),
    RESIDENT_ID    NUMBER(19),
    ASSET_ITEM_ID  NUMBER(19),
    ISSUED_DATE    DATE,
    EXPIRY_DATE    DATE,
    ISSUE_FEE      NUMBER(12) DEFAULT 0 NOT NULL,
    STATUS         VARCHAR2(20 CHAR) DEFAULT 'IN_STOCK' NOT NULL,
    NOTE           VARCHAR2(1000 CHAR),
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY     VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION        NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ACCESS_CARD PRIMARY KEY (ID),
    CONSTRAINT UK_ACCESS_CARD_NO UNIQUE (CARD_NO),
    CONSTRAINT FK_ACCESS_CARD_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_ACCESS_CARD_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_ACCESS_CARD_RESIDENT FOREIGN KEY (RESIDENT_ID) REFERENCES RESIDENT (ID),
    CONSTRAINT FK_ACCESS_CARD_ASSET_ITEM FOREIGN KEY (ASSET_ITEM_ID) REFERENCES ASSET_ITEM (ID),
    CONSTRAINT CK_ACCESS_CARD_TYPE CHECK (CARD_TYPE IN ('ELEVATOR', 'DOOR', 'PARKING', 'MULTI')),
    CONSTRAINT CK_ACCESS_CARD_STATUS CHECK (STATUS IN ('IN_USE', 'LOCKED', 'LOST', 'REVOKED', 'IN_STOCK')),
    CONSTRAINT CK_ACCESS_CARD_FEE CHECK (ISSUE_FEE >= 0),
    CONSTRAINT CK_ACCESS_CARD_DATES CHECK (EXPIRY_DATE IS NULL OR ISSUED_DATE IS NULL OR EXPIRY_DATE >= ISSUED_DATE),
    -- Đang dùng / khoá thì phải gắn căn hộ; trong kho / thu hồi thì không gắn ai.
    CONSTRAINT CK_ACCESS_CARD_ASSIGNMENT CHECK (
        (STATUS IN ('IN_USE', 'LOCKED') AND APARTMENT_ID IS NOT NULL)
        OR (STATUS IN ('IN_STOCK', 'REVOKED') AND APARTMENT_ID IS NULL AND RESIDENT_ID IS NULL AND ASSET_ITEM_ID IS NULL)
        OR STATUS = 'LOST')
);
CREATE INDEX IDX_ACCESS_CARD_BUILDING_STATUS ON ACCESS_CARD (BUILDING_ID, STATUS);
CREATE INDEX IDX_ACCESS_CARD_APARTMENT ON ACCESS_CARD (APARTMENT_ID);
CREATE INDEX IDX_ACCESS_CARD_RESIDENT ON ACCESS_CARD (RESIDENT_ID);
CREATE INDEX IDX_ACCESS_CARD_CREATED_AT ON ACCESS_CARD (CREATED_AT);
-- Một hạng mục xe chỉ liên kết với một thẻ đang dùng / khoá.
CREATE UNIQUE INDEX UK_ACCESS_CARD_ACTIVE_ITEM ON ACCESS_CARD (
    CASE WHEN STATUS IN ('IN_USE', 'LOCKED') THEN ASSET_ITEM_ID END
);
CREATE INDEX IDX_ACCESS_CARD_ASSET_ITEM ON ACCESS_CARD (ASSET_ITEM_ID);

COMMENT ON TABLE ACCESS_CARD IS 'Thẻ từ (thang máy, cửa, gửi xe, đa năng) theo tòa nhà';
COMMENT ON COLUMN ACCESS_CARD.CARD_NO IS 'Mã thẻ / serial, in hoa, duy nhất toàn hệ thống';
COMMENT ON COLUMN ACCESS_CARD.RESIDENT_ID IS 'Cư dân đang dùng thẻ (một thẻ chỉ gán một cư dân tại một thời điểm)';
COMMENT ON COLUMN ACCESS_CARD.ASSET_ITEM_ID IS 'Hạng mục xe liên kết (thẻ gửi xe / đa năng)';
COMMENT ON COLUMN ACCESS_CARD.ISSUE_FEE IS 'Phí làm thẻ (VND)';
COMMENT ON COLUMN ACCESS_CARD.STATUS IS 'IN_STOCK → IN_USE ⇄ LOCKED → LOST / REVOKED → IN_STOCK';

-- Lịch sử: lưu ảnh chụp căn hộ / cư dân dạng chữ để không chặn xoá căn hộ, cư dân về sau.
CREATE TABLE ACCESS_CARD_HISTORY (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CARD_ID         NUMBER(19) NOT NULL,
    ACTION          VARCHAR2(20 CHAR) NOT NULL,
    FROM_STATUS     VARCHAR2(20 CHAR),
    TO_STATUS       VARCHAR2(20 CHAR) NOT NULL,
    APARTMENT_LABEL VARCHAR2(150 CHAR),
    RESIDENT_NAME   VARCHAR2(150 CHAR),
    NOTE            VARCHAR2(1000 CHAR),
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY      VARCHAR2(100 CHAR) DEFAULT 'system',
    UPDATED_BY      VARCHAR2(100 CHAR) DEFAULT 'system',
    VERSION         NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ACCESS_CARD_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_ACCESS_CARD_HISTORY_CARD FOREIGN KEY (CARD_ID) REFERENCES ACCESS_CARD (ID),
    CONSTRAINT CK_ACCESS_CARD_HISTORY_ACTION CHECK (ACTION IN ('CREATED', 'ISSUED', 'STATUS_CHANGE', 'REASSIGNED'))
);
CREATE INDEX IDX_ACCESS_CARD_HISTORY_CARD ON ACCESS_CARD_HISTORY (CARD_ID, CREATED_AT);

COMMENT ON TABLE ACCESS_CARD_HISTORY IS 'Lịch sử trạng thái / gán thẻ từ';
COMMENT ON COLUMN ACCESS_CARD_HISTORY.ACTION IS 'CREATED | ISSUED (cấp thẻ) | STATUS_CHANGE | REASSIGNED (đổi căn/cư dân/xe)';
COMMENT ON COLUMN ACCESS_CARD_HISTORY.APARTMENT_LABEL IS 'Căn hộ tại thời điểm ghi (mã – tên)';
COMMENT ON COLUMN ACCESS_CARD_HISTORY.RESIDENT_NAME IS 'Cư dân tại thời điểm ghi';
