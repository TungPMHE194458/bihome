-- ---------------------------------------------------------------- Phiếu thu
CREATE TABLE PAYMENT (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID      NUMBER(19) NOT NULL,
    CODE             VARCHAR2(20 CHAR) NOT NULL,
    FEE_NOTICE_ID    NUMBER(19) NOT NULL,
    APARTMENT_ID     NUMBER(19) NOT NULL,
    AMOUNT           NUMBER(15) NOT NULL,
    METHOD           VARCHAR2(20 CHAR) NOT NULL,
    PAID_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    COLLECTOR_NAME   VARCHAR2(150 CHAR) NOT NULL,
    PAYER_NAME       VARCHAR2(150 CHAR),
    BANK_REFERENCE   VARCHAR2(100 CHAR),
    RECONCILE_STATUS VARCHAR2(20 CHAR) NOT NULL,
    NOTE             VARCHAR2(500 CHAR),
    STATUS           VARCHAR2(20 CHAR) NOT NULL,
    CANCEL_REASON    VARCHAR2(500 CHAR),
    CANCELLED_AT     TIMESTAMP WITH TIME ZONE,
    CANCELLED_BY     VARCHAR2(100 CHAR),
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY       VARCHAR2(100 CHAR),
    UPDATED_BY       VARCHAR2(100 CHAR),
    VERSION          NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PAYMENT PRIMARY KEY (ID),
    CONSTRAINT FK_PAYMENT_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_PAYMENT_FEE_NOTICE FOREIGN KEY (FEE_NOTICE_ID) REFERENCES FEE_NOTICE (ID),
    CONSTRAINT FK_PAYMENT_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT UK_PAYMENT_CODE UNIQUE (CODE),
    CONSTRAINT CK_PAYMENT_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_PAYMENT_METHOD CHECK (METHOD IN ('CASH', 'BANK_TRANSFER', 'VIETQR')),
    CONSTRAINT CK_PAYMENT_RECONCILE CHECK (RECONCILE_STATUS IN ('MATCHED', 'PENDING', 'MISMATCHED')),
    CONSTRAINT CK_PAYMENT_STATUS CHECK (STATUS IN ('VALID', 'CANCELLED')),
    CONSTRAINT CK_PAYMENT_CANCEL CHECK (STATUS <> 'CANCELLED' OR CANCEL_REASON IS NOT NULL)
);
CREATE INDEX IDX_PAYMENT_BUILDING ON PAYMENT (BUILDING_ID, PAID_AT);
CREATE INDEX IDX_PAYMENT_FEE_NOTICE ON PAYMENT (FEE_NOTICE_ID);
CREATE INDEX IDX_PAYMENT_APARTMENT ON PAYMENT (APARTMENT_ID);
CREATE INDEX IDX_PAYMENT_BANK_REFERENCE ON PAYMENT (BANK_REFERENCE);
COMMENT ON TABLE PAYMENT IS 'Phiếu thu (thanh toán thông báo phí, cho phép một phần)';
COMMENT ON COLUMN PAYMENT.RECONCILE_STATUS IS 'MATCHED đã khớp, PENDING chờ khớp (chuyển khoản nhập tay), MISMATCHED lệch số tiền';

-- ---------------------------------------------------------------- VietQR
CREATE TABLE VIETQR_CONFIG (
    BUILDING_ID      NUMBER(19) NOT NULL,
    BANK_BIN         VARCHAR2(6 CHAR) NOT NULL,
    ACCOUNT_NO       VARCHAR2(19 CHAR) NOT NULL,
    ACCOUNT_NAME     VARCHAR2(50 CHAR) NOT NULL,
    CONTENT_TEMPLATE VARCHAR2(50 CHAR) NOT NULL,
    ENABLED          NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY       VARCHAR2(100 CHAR),
    UPDATED_BY       VARCHAR2(100 CHAR),
    VERSION          NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_VIETQR_CONFIG PRIMARY KEY (BUILDING_ID),
    CONSTRAINT FK_VIETQR_CONFIG_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_VIETQR_CONFIG_BIN CHECK (REGEXP_LIKE(BANK_BIN, '^[0-9]{6}$')),
    CONSTRAINT CK_VIETQR_CONFIG_ACCOUNT CHECK (REGEXP_LIKE(ACCOUNT_NO, '^[0-9A-Z]{4,19}$')),
    CONSTRAINT CK_VIETQR_CONFIG_ENABLED CHECK (ENABLED IN (0, 1))
);
CREATE INDEX IDX_VIETQR_CONFIG_ACCOUNT ON VIETQR_CONFIG (BANK_BIN, ACCOUNT_NO);
COMMENT ON TABLE VIETQR_CONFIG IS 'Tài khoản nhận tiền VietQR của tòa';
COMMENT ON COLUMN VIETQR_CONFIG.CONTENT_TEMPLATE IS 'Mẫu nội dung chuyển khoản, bắt buộc có {MA_THONG_BAO}';

