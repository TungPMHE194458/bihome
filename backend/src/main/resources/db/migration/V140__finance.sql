    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID    NUMBER(19),
    BANK_REFERENCE VARCHAR2(100 CHAR) NOT NULL,
    ACCOUNT_NO     VARCHAR2(19 CHAR),
    AMOUNT         NUMBER(15) NOT NULL,
    CONTENT        VARCHAR2(500 CHAR),
    TRANSACTED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    MATCH_STATUS   VARCHAR2(20 CHAR) NOT NULL,
    MATCH_NOTE     VARCHAR2(300 CHAR),
