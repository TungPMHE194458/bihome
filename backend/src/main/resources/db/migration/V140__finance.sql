-- Tài chính: đơn giá, số liệu đồng hồ, thông báo phí, phiếu thu, VietQR và biến động số dư ngân hàng.
-- Tiền VND lưu số nguyên (NUMBER(15)); đơn giá điện / nước / quản lý có thể lẻ (NUMBER(15,2)).

-- ---------------------------------------------------------------- Đơn giá theo tòa
CREATE TABLE FEE_RATE_CONFIG (
    BUILDING_ID  NUMBER(19) NOT NULL,
    VAT_PERCENT  NUMBER(5,2) DEFAULT 0 NOT NULL,
    DUE_DAY      NUMBER(2) DEFAULT 15 NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(100 CHAR),
    UPDATED_BY   VARCHAR2(100 CHAR),
    VERSION      NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FEE_RATE_CONFIG PRIMARY KEY (BUILDING_ID),
    CONSTRAINT FK_FEE_RATE_CONFIG_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT CK_FEE_RATE_CONFIG_VAT CHECK (VAT_PERCENT BETWEEN 0 AND 100),
    CONSTRAINT CK_FEE_RATE_CONFIG_DUE CHECK (DUE_DAY BETWEEN 1 AND 31)
);
COMMENT ON TABLE FEE_RATE_CONFIG IS 'Cấu hình đơn giá tính thông báo phí của tòa';
COMMENT ON COLUMN FEE_RATE_CONFIG.VAT_PERCENT IS 'VAT (%) tính trên các khoản phí của kỳ (không gồm tiện ích/dịch vụ, nợ kỳ trước, giảm trừ)';
COMMENT ON COLUMN FEE_RATE_CONFIG.DUE_DAY IS 'Hạn thanh toán mặc định: ngày này của tháng sau kỳ (tháng ít ngày hơn thì ngày cuối tháng)';

CREATE TABLE FEE_MANAGEMENT_RATE (
    BUILDING_ID    NUMBER(19) NOT NULL,
    APARTMENT_TYPE VARCHAR2(30 CHAR) NOT NULL,
    UNIT_PRICE     NUMBER(15,2) NOT NULL,
    CONSTRAINT PK_FEE_MANAGEMENT_RATE PRIMARY KEY (BUILDING_ID, APARTMENT_TYPE),
    CONSTRAINT FK_FEE_MANAGEMENT_RATE_CONFIG FOREIGN KEY (BUILDING_ID) REFERENCES FEE_RATE_CONFIG (BUILDING_ID),
    CONSTRAINT CK_FEE_MANAGEMENT_RATE_PRICE CHECK (UNIT_PRICE >= 0)
);
COMMENT ON TABLE FEE_MANAGEMENT_RATE IS 'Phí quản lý (đ/m²/tháng) theo loại căn hộ';

CREATE TABLE FEE_ELECTRIC_TIER (
    BUILDING_ID NUMBER(19) NOT NULL,
    TIER_NO     NUMBER(3) NOT NULL,
    UP_TO       NUMBER(12,2),
    UNIT_PRICE  NUMBER(15,2) NOT NULL,
    CONSTRAINT PK_FEE_ELECTRIC_TIER PRIMARY KEY (BUILDING_ID, TIER_NO),
    CONSTRAINT FK_FEE_ELECTRIC_TIER_CONFIG FOREIGN KEY (BUILDING_ID) REFERENCES FEE_RATE_CONFIG (BUILDING_ID),
    CONSTRAINT CK_FEE_ELECTRIC_TIER_PRICE CHECK (UNIT_PRICE >= 0)
);
COMMENT ON TABLE FEE_ELECTRIC_TIER IS 'Giá điện bậc thang (đ/kWh); UP_TO = chỉ số tiêu thụ cộng dồn tối đa của bậc, NULL = phần còn lại';

CREATE TABLE FEE_WATER_TIER (
    BUILDING_ID NUMBER(19) NOT NULL,
    TIER_NO     NUMBER(3) NOT NULL,
    UP_TO       NUMBER(12,2),
    UNIT_PRICE  NUMBER(15,2) NOT NULL,
    CONSTRAINT PK_FEE_WATER_TIER PRIMARY KEY (BUILDING_ID, TIER_NO),
    CONSTRAINT FK_FEE_WATER_TIER_CONFIG FOREIGN KEY (BUILDING_ID) REFERENCES FEE_RATE_CONFIG (BUILDING_ID),
    CONSTRAINT CK_FEE_WATER_TIER_PRICE CHECK (UNIT_PRICE >= 0)
);
COMMENT ON TABLE FEE_WATER_TIER IS 'Giá nước bậc thang (đ/m³); UP_TO NULL = phần còn lại';

CREATE TABLE FEE_PARKING_RATE (
    BUILDING_ID       NUMBER(19) NOT NULL,
    ASSET_CATEGORY_ID NUMBER(19) NOT NULL,
    UNIT_PRICE        NUMBER(15,2) NOT NULL,
    CONSTRAINT PK_FEE_PARKING_RATE PRIMARY KEY (BUILDING_ID, ASSET_CATEGORY_ID),
    CONSTRAINT FK_FEE_PARKING_RATE_CONFIG FOREIGN KEY (BUILDING_ID) REFERENCES FEE_RATE_CONFIG (BUILDING_ID),
    CONSTRAINT FK_FEE_PARKING_RATE_CATEGORY FOREIGN KEY (ASSET_CATEGORY_ID) REFERENCES ASSET_CATEGORY (ID) ON DELETE CASCADE,
    CONSTRAINT CK_FEE_PARKING_RATE_PRICE CHECK (UNIT_PRICE >= 0)
);
CREATE INDEX IDX_FEE_PARKING_RATE_CATEGORY ON FEE_PARKING_RATE (ASSET_CATEGORY_ID);
COMMENT ON TABLE FEE_PARKING_RATE IS 'Phí gửi xe (đ/chiếc/tháng) theo danh mục tài sản; số chiếc = hạng mục đang hoạt động';

CREATE TABLE FEE_OTHER_CHARGE (
    BUILDING_ID NUMBER(19) NOT NULL,
    LINE_NO     NUMBER(3) NOT NULL,
    NAME        VARCHAR2(100 CHAR) NOT NULL,
    AMOUNT      NUMBER(15) NOT NULL,
    CONSTRAINT PK_FEE_OTHER_CHARGE PRIMARY KEY (BUILDING_ID, LINE_NO),
    CONSTRAINT FK_FEE_OTHER_CHARGE_CONFIG FOREIGN KEY (BUILDING_ID) REFERENCES FEE_RATE_CONFIG (BUILDING_ID),
    CONSTRAINT CK_FEE_OTHER_CHARGE_AMOUNT CHECK (AMOUNT >= 0)
);
COMMENT ON TABLE FEE_OTHER_CHARGE IS 'Phí khác cố định mỗi căn mỗi tháng';

-- ---------------------------------------------------------------- Số liệu đồng hồ
CREATE TABLE METER_READING (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID         NUMBER(19) NOT NULL,
    APARTMENT_ID        NUMBER(19) NOT NULL,
    BILLING_PERIOD      VARCHAR2(7 CHAR) NOT NULL,
    METER_TYPE          VARCHAR2(10 CHAR) NOT NULL,
    OLD_INDEX           NUMBER(12,2) NOT NULL,
    NEW_INDEX           NUMBER(12,2) NOT NULL,
    CONSUMPTION         NUMBER(12,2) NOT NULL,
    AVERAGE_CONSUMPTION NUMBER(12,2),
    IMAGE_FILE_ID       NUMBER(19),
    NOTE                VARCHAR2(500 CHAR),
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY          VARCHAR2(100 CHAR),
    UPDATED_BY          VARCHAR2(100 CHAR),
    VERSION             NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_METER_READING PRIMARY KEY (ID),
    CONSTRAINT FK_METER_READING_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_METER_READING_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_METER_READING_IMAGE FOREIGN KEY (IMAGE_FILE_ID) REFERENCES FILE_ATTACHMENT (ID),
    CONSTRAINT UK_METER_READING UNIQUE (APARTMENT_ID, METER_TYPE, BILLING_PERIOD),
    CONSTRAINT CK_METER_READING_TYPE CHECK (METER_TYPE IN ('ELECTRIC', 'WATER')),
    CONSTRAINT CK_METER_READING_PERIOD CHECK (REGEXP_LIKE(BILLING_PERIOD, '^[0-9]{4}-(0[1-9]|1[0-2])$')),
    CONSTRAINT CK_METER_READING_INDEX CHECK (OLD_INDEX >= 0 AND NEW_INDEX >= OLD_INDEX)
);
CREATE INDEX IDX_METER_READING_PERIOD ON METER_READING (BUILDING_ID, BILLING_PERIOD, METER_TYPE);
CREATE INDEX IDX_METER_READING_IMAGE ON METER_READING (IMAGE_FILE_ID);
COMMENT ON TABLE METER_READING IS 'Chỉ số đồng hồ điện / nước theo kỳ (yyyy-MM) của căn hộ';
COMMENT ON COLUMN METER_READING.OLD_INDEX IS 'Chỉ số mới của kỳ liền trước; chỉ nhập tay khi căn chưa có kỳ nào trước';
COMMENT ON COLUMN METER_READING.AVERAGE_CONSUMPTION IS 'Tiêu thụ trung bình tối đa 3 kỳ trước (cảnh báo khi kỳ này > 3 lần, tức tăng > 200%)';

-- ---------------------------------------------------------------- Thông báo phí
CREATE TABLE FEE_NOTICE (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUILDING_ID    NUMBER(19) NOT NULL,
    CODE           VARCHAR2(20 CHAR) NOT NULL,
    BILLING_PERIOD VARCHAR2(7 CHAR) NOT NULL,
    APARTMENT_ID   NUMBER(19) NOT NULL,
    HOLDER_NAME    VARCHAR2(150 CHAR),
    VAT_PERCENT    NUMBER(5,2) DEFAULT 0 NOT NULL,
    TOTAL_AMOUNT   NUMBER(15) DEFAULT 0 NOT NULL,
    PAID_AMOUNT    NUMBER(15) DEFAULT 0 NOT NULL,
    DUE_DATE       DATE NOT NULL,
    STATUS         VARCHAR2(20 CHAR) NOT NULL,
    ISSUED_AT      TIMESTAMP WITH TIME ZONE,
    ISSUED_BY      VARCHAR2(100 CHAR),
    CARRIED_TO_ID  NUMBER(19),
    CANCEL_REASON  VARCHAR2(500 CHAR),
    NOTE           VARCHAR2(1000 CHAR),
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(100 CHAR),
    UPDATED_BY     VARCHAR2(100 CHAR),
    VERSION        NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FEE_NOTICE PRIMARY KEY (ID),
    CONSTRAINT FK_FEE_NOTICE_BUILDING FOREIGN KEY (BUILDING_ID) REFERENCES BUILDING (ID),
    CONSTRAINT FK_FEE_NOTICE_APARTMENT FOREIGN KEY (APARTMENT_ID) REFERENCES APARTMENT (ID),
    CONSTRAINT FK_FEE_NOTICE_CARRIED_TO FOREIGN KEY (CARRIED_TO_ID) REFERENCES FEE_NOTICE (ID),
    CONSTRAINT UK_FEE_NOTICE_CODE UNIQUE (CODE),
    CONSTRAINT CK_FEE_NOTICE_PERIOD CHECK (REGEXP_LIKE(BILLING_PERIOD, '^[0-9]{4}-(0[1-9]|1[0-2])$')),
    CONSTRAINT CK_FEE_NOTICE_STATUS CHECK (STATUS IN ('DRAFT', 'ISSUED', 'PARTIAL', 'PAID', 'OVERDUE', 'CANCELLED')),
    CONSTRAINT CK_FEE_NOTICE_AMOUNT CHECK (TOTAL_AMOUNT >= 0 AND PAID_AMOUNT >= 0),
    CONSTRAINT CK_FEE_NOTICE_CANCEL CHECK (STATUS <> 'CANCELLED' OR CANCEL_REASON IS NOT NULL),
    CONSTRAINT CK_FEE_NOTICE_ISSUED CHECK (STATUS IN ('DRAFT', 'CANCELLED') OR ISSUED_AT IS NOT NULL)
);
-- Mỗi căn một thông báo phí (chưa huỷ) mỗi kỳ.
CREATE UNIQUE INDEX UK_FEE_NOTICE_APARTMENT_PERIOD ON FEE_NOTICE (
    CASE WHEN STATUS <> 'CANCELLED' THEN APARTMENT_ID END,
    CASE WHEN STATUS <> 'CANCELLED' THEN BILLING_PERIOD END);
CREATE INDEX IDX_FEE_NOTICE_PERIOD ON FEE_NOTICE (BUILDING_ID, BILLING_PERIOD, STATUS);
CREATE INDEX IDX_FEE_NOTICE_APARTMENT ON FEE_NOTICE (APARTMENT_ID, BILLING_PERIOD);
CREATE INDEX IDX_FEE_NOTICE_DUE ON FEE_NOTICE (STATUS, DUE_DATE);
CREATE INDEX IDX_FEE_NOTICE_CARRIED_TO ON FEE_NOTICE (CARRIED_TO_ID);
COMMENT ON TABLE FEE_NOTICE IS 'Thông báo phí của căn hộ theo kỳ';
COMMENT ON COLUMN FEE_NOTICE.STATUS IS 'DRAFT nháp, ISSUED đã phát hành, PARTIAL thanh toán một phần, PAID, OVERDUE quá hạn, CANCELLED huỷ';
COMMENT ON COLUMN FEE_NOTICE.HOLDER_NAME IS 'Chủ hộ tại thời điểm tạo';
COMMENT ON COLUMN FEE_NOTICE.CARRIED_TO_ID IS 'Số còn nợ đã chuyển thành "Nợ kỳ trước" của thông báo này (không thu riêng nữa)';

CREATE TABLE FEE_NOTICE_ITEM (
    FEE_NOTICE_ID NUMBER(19) NOT NULL,
    LINE_NO       NUMBER(5) NOT NULL,
    ITEM_TYPE     VARCHAR2(20 CHAR) NOT NULL,
    DESCRIPTION   VARCHAR2(300 CHAR) NOT NULL,
    QUANTITY      NUMBER(12,2),
    UNIT_PRICE    NUMBER(15,2),
    AMOUNT        NUMBER(15) NOT NULL,
    SOURCE_REF    VARCHAR2(40 CHAR),
    CONSTRAINT PK_FEE_NOTICE_ITEM PRIMARY KEY (FEE_NOTICE_ID, LINE_NO),
    CONSTRAINT FK_FEE_NOTICE_ITEM_NOTICE FOREIGN KEY (FEE_NOTICE_ID) REFERENCES FEE_NOTICE (ID),
    CONSTRAINT CK_FEE_NOTICE_ITEM_TYPE CHECK (ITEM_TYPE IN ('MANAGEMENT', 'ELECTRIC', 'WATER', 'PARKING', 'OTHER',
        'SERVICE', 'PREVIOUS_DEBT', 'VAT', 'DISCOUNT'))
);
COMMENT ON TABLE FEE_NOTICE_ITEM IS 'Các khoản của thông báo phí; DISCOUNT mang số âm';
COMMENT ON COLUMN FEE_NOTICE_ITEM.SOURCE_REF IS 'Mã giao dịch (SERVICE) / mã thông báo cũ (PREVIOUS_DEBT)';

