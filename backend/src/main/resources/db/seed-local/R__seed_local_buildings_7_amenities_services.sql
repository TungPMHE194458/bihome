-- Tiện ích, cấu hình đặt chỗ và dịch vụ mẫu (local) ở SKY01. Chỉ thêm khi chưa có.
MERGE INTO AMENITY a
USING (
    SELECT b.ID BUILDING_ID, v.*
    FROM (
        SELECT 'SKY-POOL' CODE, 'Hồ bơi' NAME, 'Tầng 5, khối A' LOCATION, 30 CAPACITY, '06:00' OPEN_TIME, '21:00' CLOSE_TIME,
               'Mặc đồ bơi; trẻ em dưới 12 tuổi phải có người lớn đi kèm.' RULES, 0 REQUIRES_APPROVAL FROM DUAL UNION ALL
        SELECT 'SKY-GYM', 'Phòng gym', 'Tầng 5, khối B', 20, '05:30', '22:00', 'Mang giày thể thao, lau dụng cụ sau khi dùng.', 0 FROM DUAL UNION ALL
        SELECT 'SKY-BBQ', 'Khu BBQ', 'Sân thượng', 15, '16:00', '22:00', 'Dọn dẹp sau khi sử dụng; không dùng than tổ ong.', 1 FROM DUAL
    ) v
    JOIN BUILDING b ON b.CODE = 'SKY01'
) s
ON (a.CODE = s.CODE)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, CODE, NAME, LOCATION, CAPACITY, OPEN_TIME, CLOSE_TIME, RULES, REQUIRES_APPROVAL, STATUS, CREATED_BY, UPDATED_BY)
    VALUES (s.BUILDING_ID, s.CODE, s.NAME, s.LOCATION, s.CAPACITY, s.OPEN_TIME, s.CLOSE_TIME, s.RULES, s.REQUIRES_APPROVAL,
            'ACTIVE', 'admin', 'admin');

INSERT INTO AMENITY_CONFIG (AMENITY_ID, SLOT_MINUTES, MAX_BOOKINGS_PER_WEEK, MAX_ADVANCE_DAYS, FREE_CANCEL_HOURS, CREATED_BY, UPDATED_BY)
SELECT a.ID, CASE a.CODE WHEN 'SKY-BBQ' THEN 180 ELSE 60 END, CASE a.CODE WHEN 'SKY-BBQ' THEN 1 ELSE 5 END,
       CASE a.CODE WHEN 'SKY-BBQ' THEN 14 ELSE 7 END, CASE a.CODE WHEN 'SKY-BBQ' THEN 24 ELSE 2 END, 'admin', 'admin'
FROM AMENITY a
WHERE a.CODE IN ('SKY-POOL', 'SKY-GYM', 'SKY-BBQ')
  AND NOT EXISTS (SELECT 1 FROM AMENITY_CONFIG c WHERE c.AMENITY_ID = a.ID);

-- Hồ bơi: mỗi ngày các lượt 1 giờ từ 06:00 đến 21:00 (chỉ sinh khi chưa có khung giờ nào).
INSERT INTO AMENITY_SLOT (AMENITY_ID, DAY_OF_WEEK, START_TIME, END_TIME)
SELECT a.ID, d.DAY_NO, LPAD(h.HOUR_NO, 2, '0') || ':00', LPAD(h.HOUR_NO + 1, 2, '0') || ':00'
FROM AMENITY a
CROSS JOIN (SELECT LEVEL DAY_NO FROM DUAL CONNECT BY LEVEL <= 7) d
CROSS JOIN (SELECT LEVEL + 5 HOUR_NO FROM DUAL CONNECT BY LEVEL <= 15) h
WHERE a.CODE = 'SKY-POOL'
  AND NOT EXISTS (SELECT 1 FROM AMENITY_SLOT s WHERE s.AMENITY_ID = a.ID);

-- Khu BBQ: 2 lượt buổi tối, chỉ thứ 6 – chủ nhật.
INSERT INTO AMENITY_SLOT (AMENITY_ID, DAY_OF_WEEK, START_TIME, END_TIME)
SELECT a.ID, d.DAY_NO, t.START_TIME, t.END_TIME
FROM AMENITY a
CROSS JOIN (SELECT LEVEL + 4 DAY_NO FROM DUAL CONNECT BY LEVEL <= 3) d
CROSS JOIN (SELECT '16:00' START_TIME, '19:00' END_TIME FROM DUAL UNION ALL SELECT '19:00', '22:00' FROM DUAL) t
WHERE a.CODE = 'SKY-BBQ'
  AND NOT EXISTS (SELECT 1 FROM AMENITY_SLOT s WHERE s.AMENITY_ID = a.ID);

INSERT INTO AMENITY_PRICE (AMENITY_ID, DAY_TYPE, START_TIME, END_TIME, PRICE, PRICE_UNIT)
SELECT a.ID, p.DAY_TYPE, p.START_TIME, p.END_TIME, p.PRICE, p.PRICE_UNIT
FROM AMENITY a
JOIN (
    SELECT 'SKY-POOL' CODE, 'WEEKEND' DAY_TYPE, '06:00' START_TIME, '21:00' END_TIME, 30000 PRICE, 'PER_PERSON' PRICE_UNIT FROM DUAL UNION ALL
    SELECT 'SKY-POOL', 'WEEKDAY', '17:00', '21:00', 20000, 'PER_PERSON' FROM DUAL UNION ALL
    SELECT 'SKY-BBQ', 'WEEKDAY', '16:00', '22:00', 300000, 'PER_BOOKING' FROM DUAL UNION ALL
    SELECT 'SKY-BBQ', 'WEEKEND', '16:00', '22:00', 500000, 'PER_BOOKING' FROM DUAL
) p ON p.CODE = a.CODE
WHERE NOT EXISTS (SELECT 1 FROM AMENITY_PRICE x WHERE x.AMENITY_ID = a.ID);

MERGE INTO SERVICE s
USING (
    SELECT b.ID BUILDING_ID, v.CODE, v.NAME, t.ID TYPE_ID, v.PRICE, v.UNIT, v.DESCRIPTION
    FROM (
        SELECT 'DV0001' CODE, 'Vệ sinh căn hộ theo giờ' NAME, 'Vệ sinh' TYPE_NAME, 120000 PRICE, 'giờ' UNIT,
               'Lau dọn, hút bụi toàn căn' DESCRIPTION FROM DUAL UNION ALL
        SELECT 'DV0002', 'Sửa điện nước', 'Sửa chữa', 150000, 'lần', 'Thay bóng đèn, ổ cắm, vòi nước' FROM DUAL UNION ALL
        SELECT 'DV0003', 'Giặt sofa', 'Vệ sinh', 80000, 'm²', NULL FROM DUAL UNION ALL
        SELECT 'DV0004', 'Giặt sấy quần áo', 'Giặt là', 25000, 'kg', 'Nhận và trả tại sảnh' FROM DUAL
    ) v
    JOIN BUILDING b ON b.CODE = 'SKY01'
    JOIN SERVICE_TYPE t ON t.NAME = v.TYPE_NAME
) x
ON (s.BUILDING_ID = x.BUILDING_ID AND s.CODE = x.CODE)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, CODE, NAME, SERVICE_TYPE_ID, UNIT_PRICE, UNIT, DESCRIPTION, STATUS, CREATED_BY, UPDATED_BY)
    VALUES (x.BUILDING_ID, x.CODE, x.NAME, x.TYPE_ID, x.PRICE, x.UNIT, x.DESCRIPTION, 'ACTIVE', 'admin', 'admin');
