-- Đăng ký tiện ích, đơn dịch vụ và giao dịch mẫu (local) ở SKY01. Chỉ thêm khi chưa có (theo mã).
-- Ngày tính theo tuần ISO hiện tại: IW = thứ 2 tuần này; +7 = thứ 2 tuần sau; +11 = thứ 6 tuần sau; +12 = thứ 7 tuần sau.
MERGE INTO AMENITY_BOOKING k
USING (
    SELECT b.ID BUILDING_ID, x.CODE, am.ID AMENITY_ID, ap.ID APARTMENT_ID, r.ID RESIDENT_ID, x.BOOKING_DATE,
           x.START_TIME, x.END_TIME, x.PEOPLE, x.UNIT_PRICE, x.PRICE_UNIT, x.FEE, x.STATUS, x.CANCEL_REASON, x.NOTE
    FROM (
        SELECT 'DK-261001-001' CODE, 'SKY-POOL' AMENITY, 'A0101' APT, 'CD000002' RES, TRUNC(SYSDATE, 'IW') + 7 BOOKING_DATE,
               '07:00' START_TIME, '08:00' END_TIME, 3 PEOPLE, 0 UNIT_PRICE, NULL PRICE_UNIT, 0 FEE, 'APPROVED' STATUS,
               NULL CANCEL_REASON, 'Bơi buổi sáng cùng con' NOTE FROM DUAL UNION ALL
        SELECT 'DK-261001-002', 'SKY-POOL', 'A0201', 'CD000005', TRUNC(SYSDATE, 'IW') + 7, '07:00', '08:00', 2, 0, NULL, 0,
               'APPROVED', NULL, NULL FROM DUAL UNION ALL
        SELECT 'DK-261001-003', 'SKY-POOL', 'A0102', 'CD000004', TRUNC(SYSDATE, 'IW') - 7, '06:00', '07:00', 2, 0, NULL, 0,
               'COMPLETED', NULL, NULL FROM DUAL UNION ALL
        SELECT 'DK-261001-004', 'SKY-BBQ', 'A0201', 'CD000005', TRUNC(SYSDATE, 'IW') + 11, '19:00', '22:00', 10, 300000,
               'PER_BOOKING', 300000, 'PENDING', NULL, 'Sinh nhật bé, cần thêm 2 bàn' FROM DUAL UNION ALL
        SELECT 'DK-261001-005', 'SKY-BBQ', 'A0101', 'CD000002', TRUNC(SYSDATE, 'IW') + 12, '16:00', '19:00', 8, 500000,
               'PER_BOOKING', 500000, 'APPROVED', NULL, NULL FROM DUAL UNION ALL
        SELECT 'DK-261001-006', 'SKY-POOL', 'A0102', 'CD000004', TRUNC(SYSDATE, 'IW') - 7, '18:00', '19:00', 2, 20000,
               'PER_PERSON', 40000, 'CANCELLED', 'Bận việc đột xuất', NULL FROM DUAL
    ) x
    JOIN BUILDING b ON b.CODE = 'SKY01'
    JOIN AMENITY am ON am.BUILDING_ID = b.ID AND am.CODE = x.AMENITY
    JOIN APARTMENT ap ON ap.BUILDING_ID = b.ID AND ap.CODE = x.APT
    LEFT JOIN RESIDENT r ON r.BUILDING_ID = b.ID AND r.CODE = x.RES
) s
ON (k.CODE = s.CODE)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, CODE, AMENITY_ID, APARTMENT_ID, RESIDENT_ID, BOOKING_DATE, START_TIME, END_TIME, PEOPLE_COUNT,
            UNIT_PRICE, PRICE_UNIT, FEE, DISCOUNT, TOTAL, STATUS, NOTE, CANCEL_REASON, DECIDED_AT, DECIDED_BY,
            CANCELLED_AT, COMPLETED_AT, CREATED_BY, UPDATED_BY)
    VALUES (s.BUILDING_ID, s.CODE, s.AMENITY_ID, s.APARTMENT_ID, s.RESIDENT_ID, s.BOOKING_DATE, s.START_TIME, s.END_TIME,
            s.PEOPLE, s.UNIT_PRICE, s.PRICE_UNIT, s.FEE, 0, s.FEE, s.STATUS, s.NOTE, s.CANCEL_REASON,
            CASE WHEN s.STATUS IN ('APPROVED', 'COMPLETED') THEN SYSTIMESTAMP END,
            CASE WHEN s.STATUS IN ('APPROVED', 'COMPLETED') THEN 'admin' END,
            CASE WHEN s.STATUS = 'CANCELLED' THEN SYSTIMESTAMP END,
            CASE WHEN s.STATUS = 'COMPLETED' THEN SYSTIMESTAMP END, 'admin', 'admin');

MERGE INTO SERVICE_ORDER o
USING (
    SELECT b.ID BUILDING_ID, x.CODE, sv.ID SERVICE_ID, ap.ID APARTMENT_ID, r.ID RESIDENT_ID, x.QUANTITY, sv.UNIT_PRICE,
           sv.UNIT, ROUND(sv.UNIT_PRICE * x.QUANTITY) AMOUNT, x.SCHEDULED_AT, x.STATUS, x.NOTE
    FROM (
        SELECT 'DV-261001-001' CODE, 'DV0001' SERVICE, 'A0101' APT, 'CD000002' RES, 3 QUANTITY,
               FROM_TZ(CAST(TRUNC(SYSDATE, 'IW') + 8 + 9 / 24 AS TIMESTAMP), 'Asia/Ho_Chi_Minh') SCHEDULED_AT,
               'CONFIRMED' STATUS, 'Vệ sinh tổng trước Tết' NOTE FROM DUAL UNION ALL
        SELECT 'DV-261001-002', 'DV0003', 'A0201', 'CD000005', 4.5, NULL, 'COMPLETED', NULL FROM DUAL
    ) x
    JOIN BUILDING b ON b.CODE = 'SKY01'
    JOIN SERVICE sv ON sv.BUILDING_ID = b.ID AND sv.CODE = x.SERVICE
    JOIN APARTMENT ap ON ap.BUILDING_ID = b.ID AND ap.CODE = x.APT
    LEFT JOIN RESIDENT r ON r.BUILDING_ID = b.ID AND r.CODE = x.RES
) s
ON (o.CODE = s.CODE)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, CODE, SERVICE_ID, APARTMENT_ID, RESIDENT_ID, QUANTITY, UNIT_PRICE, UNIT, AMOUNT, DISCOUNT, TOTAL,
            SCHEDULED_AT, STATUS, NOTE, COMPLETED_AT, CREATED_BY, UPDATED_BY)
    VALUES (s.BUILDING_ID, s.CODE, s.SERVICE_ID, s.APARTMENT_ID, s.RESIDENT_ID, s.QUANTITY, s.UNIT_PRICE, s.UNIT, s.AMOUNT,
            0, s.AMOUNT, s.SCHEDULED_AT, s.STATUS, s.NOTE, CASE WHEN s.STATUS = 'COMPLETED' THEN SYSTIMESTAMP END,
            'admin', 'admin');

-- Giao dịch của các nguồn mẫu có phí (mã GD theo thứ tự nguồn để không trùng khi chạy lại).
MERGE INTO FINANCIAL_TRANSACTION t
USING (
    SELECT x.*, 'GD-261001-' || LPAD(ROW_NUMBER() OVER (ORDER BY x.SOURCE_TYPE, x.SOURCE_CODE), 3, '0') CODE
    FROM (
        SELECT k.BUILDING_ID, 'AMENITY_BOOKING' SOURCE_TYPE, k.ID SOURCE_ID, k.CODE SOURCE_CODE, k.APARTMENT_ID,
               k.RESIDENT_ID, k.TOTAL AMOUNT,
               CASE k.CODE WHEN 'DK-261001-005' THEN 'BANK_TRANSFER' END METHOD,
               CASE k.CODE WHEN 'DK-261001-005' THEN 'PAID' WHEN 'DK-261001-006' THEN 'CANCELLED' ELSE 'PENDING' END STATUS,
               'Phí sử dụng ' || a.NAME || ' ' || k.START_TIME || '–' || k.END_TIME || ' ' || TO_CHAR(k.BOOKING_DATE, 'DD/MM/YYYY') DESCRIPTION
        FROM AMENITY_BOOKING k JOIN AMENITY a ON a.ID = k.AMENITY_ID
        WHERE k.CODE LIKE 'DK-261001-%' AND k.TOTAL > 0
        UNION ALL
        SELECT o.BUILDING_ID, 'SERVICE_ORDER', o.ID, o.CODE, o.APARTMENT_ID, o.RESIDENT_ID, o.TOTAL,
               CASE o.STATUS WHEN 'COMPLETED' THEN 'CASH' END,
               CASE o.STATUS WHEN 'COMPLETED' THEN 'PAID' ELSE 'PENDING' END,
               sv.NAME || ' × ' || TO_CHAR(o.QUANTITY, 'FM99990.99') || ' ' || o.UNIT
        FROM SERVICE_ORDER o JOIN SERVICE sv ON sv.ID = o.SERVICE_ID
        WHERE o.CODE LIKE 'DV-261001-%' AND o.TOTAL > 0
        UNION ALL
        SELECT c.BUILDING_ID, 'ACCESS_CARD', c.ID, c.CARD_NO, c.APARTMENT_ID, c.RESIDENT_ID, c.ISSUE_FEE, 'CASH', 'PAID',
               'Phí làm thẻ ' || c.CARD_NO
        FROM ACCESS_CARD c JOIN BUILDING b ON b.ID = c.BUILDING_ID
        WHERE b.CODE = 'SKY01' AND c.ISSUE_FEE > 0 AND c.STATUS IN ('IN_USE', 'LOCKED')
    ) x
) s
ON (t.SOURCE_TYPE = s.SOURCE_TYPE AND t.SOURCE_ID = s.SOURCE_ID)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, CODE, SOURCE_TYPE, SOURCE_ID, SOURCE_CODE, APARTMENT_ID, RESIDENT_ID, AMOUNT, METHOD, STATUS,
            DESCRIPTION, PAID_AT, CREATED_BY, UPDATED_BY)
    VALUES (s.BUILDING_ID, s.CODE, s.SOURCE_TYPE, s.SOURCE_ID, s.SOURCE_CODE, s.APARTMENT_ID, s.RESIDENT_ID, s.AMOUNT,
            s.METHOD, s.STATUS, s.DESCRIPTION, CASE WHEN s.STATUS = 'PAID' THEN SYSTIMESTAMP END, 'admin', 'admin');
