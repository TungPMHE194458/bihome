-- Thẻ từ và voucher mẫu (local, dữ liệu giả). Tên file sắp sau cư dân / hạng mục xe.
MERGE INTO ACCESS_CARD c
USING (
    SELECT b.ID BUILDING_ID, v.CARD_NO, v.CARD_TYPE, a.ID APARTMENT_ID, r.ID RESIDENT_ID, i.ID ASSET_ITEM_ID,
           v.STATUS, v.ISSUED, v.EXPIRY, v.FEE
    FROM (
        SELECT 'SKY-0001' CARD_NO, 'MULTI' CARD_TYPE, 'A0101' APT, 'CD000001' RES, CAST(NULL AS VARCHAR2(30)) PLATE,
               'IN_USE' STATUS, DATE '2024-03-01' ISSUED, DATE '2027-03-01' EXPIRY, 100000 FEE FROM DUAL UNION ALL
        SELECT 'SKY-0002', 'PARKING', 'A0101', 'CD000001', '30A-123.45', 'IN_USE', DATE '2025-01-15', NULL, 50000 FROM DUAL UNION ALL
        SELECT 'SKY-0003', 'ELEVATOR', 'A0101', 'CD000002', NULL, 'IN_USE', DATE '2024-03-01', DATE '2026-03-01', 50000 FROM DUAL UNION ALL
        SELECT 'SKY-0004', 'DOOR', 'A0102', 'CD000004', NULL, 'LOCKED', DATE '2023-10-15', NULL, 50000 FROM DUAL UNION ALL
        SELECT 'SKY-0005', 'ELEVATOR', 'A0201', 'CD000005', NULL, 'LOST', DATE '2024-06-01', NULL, 50000 FROM DUAL UNION ALL
        SELECT 'SKY-0006', 'MULTI', NULL, NULL, NULL, 'IN_STOCK', NULL, NULL, 100000 FROM DUAL UNION ALL
        SELECT 'SKY-0007', 'PARKING', NULL, NULL, NULL, 'IN_STOCK', NULL, NULL, 50000 FROM DUAL
    ) v
    JOIN BUILDING b ON b.CODE = 'SKY01'
    LEFT JOIN APARTMENT a ON a.BUILDING_ID = b.ID AND a.CODE = v.APT
    LEFT JOIN RESIDENT r ON r.BUILDING_ID = b.ID AND r.CODE = v.RES
    LEFT JOIN ASSET_ITEM i ON i.APARTMENT_ID = a.ID AND i.PLATE_NUMBER = v.PLATE
) s
ON (c.CARD_NO = s.CARD_NO)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, CARD_NO, CARD_TYPE, APARTMENT_ID, RESIDENT_ID, ASSET_ITEM_ID, ISSUED_DATE, EXPIRY_DATE, ISSUE_FEE,
            STATUS, CREATED_BY, UPDATED_BY)
    VALUES (s.BUILDING_ID, s.CARD_NO, s.CARD_TYPE, s.APARTMENT_ID, s.RESIDENT_ID, s.ASSET_ITEM_ID, s.ISSUED, s.EXPIRY, s.FEE,
            s.STATUS, 'admin', 'admin');

-- Mục lịch sử đầu tiên cho thẻ mẫu chưa có.
INSERT INTO ACCESS_CARD_HISTORY (CARD_ID, ACTION, TO_STATUS, APARTMENT_LABEL, RESIDENT_NAME, CREATED_BY, UPDATED_BY)
SELECT c.ID, CASE WHEN c.APARTMENT_ID IS NULL THEN 'CREATED' ELSE 'ISSUED' END,
       CASE WHEN c.APARTMENT_ID IS NULL THEN 'IN_STOCK' ELSE 'IN_USE' END,
       CASE WHEN a.ID IS NOT NULL THEN a.CODE || ' – ' || a.NAME END, r.FULL_NAME, 'admin', 'admin'
FROM ACCESS_CARD c
LEFT JOIN APARTMENT a ON a.ID = c.APARTMENT_ID
LEFT JOIN RESIDENT r ON r.ID = c.RESIDENT_ID
WHERE c.CARD_NO LIKE 'SKY-%'
  AND NOT EXISTS (SELECT 1 FROM ACCESS_CARD_HISTORY h WHERE h.CARD_ID = c.ID);

MERGE INTO VOUCHER v
USING (
    SELECT b.ID BUILDING_ID, x.*
    FROM (
        SELECT 'HOBOI10' CODE, 'Giảm 10% vé hồ bơi' NAME, 'PERCENT' DISCOUNT_TYPE, 10 DISCOUNT_VALUE,
               50000 MAX_DISCOUNT, 'AMENITY' APPLY_SCOPE, 200 TOTAL_QUANTITY, 2 PER_APT,
               TRUNC(SYSDATE) - 10 VALID_FROM, TRUNC(SYSDATE) + 50 VALID_TO, 'ACTIVE' STATUS FROM DUAL UNION ALL
        SELECT 'GYM50K', 'Giảm 50.000đ phòng gym', 'AMOUNT', 50000, NULL, 'AMENITY', 100, 1,
               TRUNC(SYSDATE) - 90, TRUNC(SYSDATE) - 30, 'ACTIVE' FROM DUAL UNION ALL
        SELECT 'TET2027', 'Ưu đãi Tết dịch vụ', 'PERCENT', 15, 100000, 'SERVICE', NULL, 3,
               TRUNC(SYSDATE) + 60, TRUNC(SYSDATE) + 90, 'ACTIVE' FROM DUAL UNION ALL
        SELECT 'CUDAN5', 'Giảm 5% mọi tiện ích, dịch vụ', 'PERCENT', 5, NULL, 'ALL', NULL, NULL,
               TRUNC(SYSDATE) - 30, TRUNC(SYSDATE) + 300, 'INACTIVE' FROM DUAL
    ) x
    JOIN BUILDING b ON b.CODE = 'SKY01'
) s
ON (v.CODE = s.CODE)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, CODE, NAME, DISCOUNT_TYPE, DISCOUNT_VALUE, MAX_DISCOUNT, APPLY_SCOPE, TOTAL_QUANTITY,
            PER_APARTMENT_LIMIT, VALID_FROM, VALID_TO, STATUS, CREATED_BY, UPDATED_BY)
    VALUES (s.BUILDING_ID, s.CODE, s.NAME, s.DISCOUNT_TYPE, s.DISCOUNT_VALUE, s.MAX_DISCOUNT, s.APPLY_SCOPE,
            s.TOTAL_QUANTITY, s.PER_APT, s.VALID_FROM, s.VALID_TO, s.STATUS, 'admin', 'admin');
