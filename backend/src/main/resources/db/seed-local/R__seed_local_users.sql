-- Chỉ chạy ở profile local. Tài khoản admin / Admin@123 (Admin hệ thống).
-- MERGE ... WHEN NOT MATCHED để không ghi đè nếu đã đổi mật khẩu trên máy local.

MERGE INTO APP_USER u
USING (SELECT 'admin' USERNAME FROM DUAL) s
ON (u.USERNAME = s.USERNAME)
WHEN NOT MATCHED THEN
    INSERT (USERNAME, EMAIL, PASSWORD_HASH, STATUS, PASSWORD_CHANGED_AT)
    VALUES ('admin', 'admin@bihome.local', '$2a$10$r35l6j2An4BGDofZu5HM9eN4E1lUzVkRGhi/gPt0YA09Ao3OuAs/G', 'ACTIVE',
            SYSTIMESTAMP);

MERGE INTO USER_PROFILE p
USING (SELECT ID FROM APP_USER WHERE USERNAME = 'admin') s
ON (p.USER_ID = s.ID)
WHEN NOT MATCHED THEN
    INSERT (USER_ID, FULL_NAME, JOB_TITLE) VALUES (s.ID, 'Hân', 'Admin hệ thống');

MERGE INTO USER_ROLE ur
USING (SELECT u.ID USER_ID, r.ID ROLE_ID FROM APP_USER u CROSS JOIN ROLE r
       WHERE u.USERNAME = 'admin' AND r.CODE = 'SUPER_ADMIN') s
ON (ur.USER_ID = s.USER_ID AND ur.ROLE_ID = s.ROLE_ID)
WHEN NOT MATCHED THEN
    INSERT (USER_ID, ROLE_ID) VALUES (s.USER_ID, s.ROLE_ID);
