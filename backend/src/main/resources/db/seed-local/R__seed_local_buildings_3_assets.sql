-- Danh mục & hạng mục xe mẫu (local). Tên file sắp sau căn hộ để chạy khi đã có căn hộ.
MERGE INTO ASSET_CATEGORY c
USING (
    SELECT b.ID BUILDING_ID, v.NAME, v.UNIT, v.DESCRIPTION
    FROM BUILDING b
    CROSS JOIN (
        SELECT 'Ô tô' NAME, 'chiếc' UNIT, 'Xe ô tô gửi tại hầm' DESCRIPTION FROM DUAL UNION ALL
        SELECT 'Xe máy', 'chiếc', 'Xe máy, xe tay ga' FROM DUAL UNION ALL
        SELECT 'Xe đạp', 'chiếc', NULL FROM DUAL UNION ALL
        SELECT 'Xe điện', 'chiếc', 'Xe máy điện, xe đạp điện' FROM DUAL
    ) v
    WHERE b.CODE IN ('SKY01', 'GRD01')
) s
ON (c.BUILDING_ID = s.BUILDING_ID AND LOWER(c.NAME) = LOWER(s.NAME))
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, NAME, UNIT, DESCRIPTION, STATUS) VALUES (s.BUILDING_ID, s.NAME, s.UNIT, s.DESCRIPTION, 'ACTIVE');

MERGE INTO ASSET_ITEM i
USING (
    SELECT a.BUILDING_ID, a.ID APARTMENT_ID, c.ID CATEGORY_ID, v.NAME, v.PLATE, v.ENTRY_DATE
    FROM (
        SELECT 'A0101' APT, 'Ô tô' CAT, 'Toyota Vios trắng' NAME, '30A-123.45' PLATE, DATE '2025-01-15' ENTRY_DATE FROM DUAL UNION ALL
        SELECT 'A0101', 'Xe máy', 'Honda Vision đỏ', '29B1-678.90', DATE '2025-01-15' FROM DUAL UNION ALL
        SELECT 'A0102', 'Xe máy', 'Yamaha Janus xanh', '29F1-246.80', DATE '2025-03-02' FROM DUAL UNION ALL
        SELECT 'A0201', 'Ô tô', 'Mazda CX-5 đen', '30G-555.66', DATE '2025-06-20' FROM DUAL UNION ALL
        SELECT 'A0203', 'Xe điện', 'VinFast Evo200', '29MĐ1-012.34', DATE '2025-08-01' FROM DUAL UNION ALL
        SELECT 'A0304', 'Xe đạp', 'Xe đạp Giant', NULL, DATE '2025-09-10' FROM DUAL
    ) v
    JOIN BUILDING b ON b.CODE = 'SKY01'
    JOIN APARTMENT a ON a.BUILDING_ID = b.ID AND a.CODE = v.APT
    JOIN ASSET_CATEGORY c ON c.BUILDING_ID = b.ID AND c.NAME = v.CAT
) s
ON (i.APARTMENT_ID = s.APARTMENT_ID AND i.NAME = s.NAME)
WHEN NOT MATCHED THEN
    INSERT (BUILDING_ID, APARTMENT_ID, CATEGORY_ID, NAME, PLATE_NUMBER, UNIT, ENTRY_DATE, STATUS)
    VALUES (s.BUILDING_ID, s.APARTMENT_ID, s.CATEGORY_ID, s.NAME, s.PLATE, 'chiếc', s.ENTRY_DATE, 'ACTIVE');
