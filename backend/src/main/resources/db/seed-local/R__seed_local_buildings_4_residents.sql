MERGE INTO APARTMENT_RESIDENT ar
USING (
    SELECT r.ID RESIDENT_ID, a.ID APARTMENT_ID, v.ROLE_CODE, v.REL, v.IS_PRIMARY, v.MOVE_IN, v.MOVE_OUT, v.STATUS, v.TEMP
    FROM (
        SELECT 'CD000001' CODE, 'A0101' APT, 'OWNER' ROLE_CODE, NULL REL, 1 IS_PRIMARY, DATE '2024-03-01' MOVE_IN,
               CAST(NULL AS DATE) MOVE_OUT, 'LIVING' STATUS, 1 TEMP FROM DUAL UNION ALL
        SELECT 'CD000002', 'A0101', 'FAMILY', 'SPOUSE', 0, DATE '2024-03-01', NULL, 'LIVING', 1 FROM DUAL UNION ALL
        SELECT 'CD000003', 'A0101', 'FAMILY', 'CHILD', 0, DATE '2024-03-01', NULL, 'LIVING', 1 FROM DUAL UNION ALL
        SELECT 'CD000004', 'A0102', 'OWNER', NULL, 1, DATE '2023-10-15', NULL, 'LIVING', 0 FROM DUAL UNION ALL
        SELECT 'CD000004', 'A0201', 'OWNER', NULL, 1, DATE '2024-05-01', NULL, 'LIVING', 0 FROM DUAL UNION ALL
        SELECT 'CD000005', 'A0201', 'TENANT', NULL, 0, DATE '2024-06-01', NULL, 'LIVING', 1 FROM DUAL UNION ALL
        SELECT 'CD000006', 'A0203', 'TENANT', NULL, 0, DATE '2025-01-10', NULL, 'TEMP_ABSENT', 1 FROM DUAL UNION ALL
        SELECT 'CD000007', 'A0304', 'GUEST', NULL, 0, DATE '2025-09-01', NULL, 'LIVING', 1 FROM DUAL UNION ALL
        SELECT 'CD000008', 'A0102', 'TENANT', NULL, 0, DATE '2023-01-01', DATE '2023-09-30', 'MOVED_OUT', 1 FROM DUAL
    ) v
    JOIN BUILDING b ON b.CODE = 'SKY01'
    JOIN RESIDENT r ON r.BUILDING_ID = b.ID AND r.CODE = v.CODE
    JOIN APARTMENT a ON a.BUILDING_ID = b.ID AND a.CODE = v.APT
) s
ON (ar.RESIDENT_ID = s.RESIDENT_ID AND ar.APARTMENT_ID = s.APARTMENT_ID)
WHEN NOT MATCHED THEN
    INSERT (RESIDENT_ID, APARTMENT_ID, RESIDENT_ROLE, RELATIONSHIP, IS_PRIMARY, MOVE_IN_DATE, MOVE_OUT_DATE,
            RESIDENCE_STATUS, TEMP_RESIDENCE_REGISTERED)
    VALUES (s.RESIDENT_ID, s.APARTMENT_ID, s.ROLE_CODE, s.REL, s.IS_PRIMARY, s.MOVE_IN, s.MOVE_OUT, s.STATUS, s.TEMP);
