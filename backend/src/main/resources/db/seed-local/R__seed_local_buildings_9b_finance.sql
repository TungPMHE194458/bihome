-- Chỉ số 2 kỳ trước tháng hiện tại (kỳ cũ = P2, kỳ gần = P1); căn A0203 tăng điện bất thường ở kỳ gần.
INSERT INTO METER_READING (BUILDING_ID, APARTMENT_ID, BILLING_PERIOD, METER_TYPE, OLD_INDEX, NEW_INDEX, CONSUMPTION,
                           AVERAGE_CONSUMPTION, CREATED_BY, UPDATED_BY)
WITH base AS (
    SELECT a.ID, a.BUILDING_ID, a.CODE,
           TO_CHAR(ADD_MONTHS(SYSDATE, -2), 'YYYY-MM') P2,
           TO_CHAR(ADD_MONTHS(SYSDATE, -1), 'YYYY-MM') P1,
           2000 + MOD(a.ID * 7, 23) * 40 E_OLD,
           180 + MOD(a.ID * 13, 90) E_C2,
           CASE WHEN a.CODE = 'A0203' THEN 820 ELSE 190 + MOD(a.ID * 11, 80) END E_C1,
           100 + MOD(a.ID * 7, 23) * 3 W_OLD,
           12 + MOD(a.ID, 6) W_C2,
           13 + MOD(a.ID * 3, 6) W_C1
    FROM APARTMENT a JOIN BUILDING b ON b.ID = a.BUILDING_ID
    WHERE b.CODE = 'SKY01' AND a.STATUS = 'ACTIVE'
), rows_ AS (
    SELECT ID, BUILDING_ID, P2 PERIOD, 'ELECTRIC' T, E_OLD O, E_OLD + E_C2 N, E_C2 C, CAST(NULL AS NUMBER) AVG_C FROM base
    UNION ALL
    SELECT ID, BUILDING_ID, P1, 'ELECTRIC', E_OLD + E_C2, E_OLD + E_C2 + E_C1, E_C1, E_C2 FROM base
    UNION ALL
    SELECT ID, BUILDING_ID, P2, 'WATER', W_OLD, W_OLD + W_C2, W_C2, NULL FROM base
    UNION ALL
    SELECT ID, BUILDING_ID, P1, 'WATER', W_OLD + W_C2, W_OLD + W_C2 + W_C1, W_C1, W_C2 FROM base
)
SELECT r.BUILDING_ID, r.ID, r.PERIOD, r.T, r.O, r.N, r.C, r.AVG_C, 'admin', 'admin'
FROM rows_ r
WHERE NOT EXISTS (SELECT 1 FROM METER_READING m WHERE m.APARTMENT_ID = r.ID AND m.METER_TYPE = r.T
                  AND m.BILLING_PERIOD = r.PERIOD)
  -- Đã có số liệu (nhập tay) của đồng hồ thì không chèn thêm để chuỗi chỉ số không bị lệch.
  AND NOT EXISTS (SELECT 1 FROM METER_READING m WHERE m.APARTMENT_ID = r.ID AND m.METER_TYPE = r.T);
