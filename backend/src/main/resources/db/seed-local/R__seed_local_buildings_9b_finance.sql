-- Tài chính mẫu (local) ở SKY01: đơn giá, tài khoản VietQR (số tài khoản giả) và chỉ số điện / nước 2 kỳ gần nhất
-- của mọi căn để thử "Tạo hàng loạt" thông báo phí. Chỉ thêm khi chưa có (không ghi đè chỉnh sửa trên màn hình).

INSERT INTO FEE_RATE_CONFIG (BUILDING_ID, VAT_PERCENT, DUE_DAY, CREATED_BY, UPDATED_BY)
SELECT b.ID, 8, 15, 'admin', 'admin' FROM BUILDING b
WHERE b.CODE = 'SKY01' AND NOT EXISTS (SELECT 1 FROM FEE_RATE_CONFIG c WHERE c.BUILDING_ID = b.ID);

INSERT INTO FEE_MANAGEMENT_RATE (BUILDING_ID, APARTMENT_TYPE, UNIT_PRICE)
SELECT b.ID, v.T, v.P
FROM BUILDING b
CROSS JOIN (SELECT 'APARTMENT' T, 12000 P FROM DUAL UNION ALL SELECT 'PENTHOUSE', 18000 FROM DUAL
            UNION ALL SELECT 'DUPLEX', 15000 FROM DUAL UNION ALL SELECT 'SHOPHOUSE', 25000 FROM DUAL) v
WHERE b.CODE = 'SKY01' AND NOT EXISTS (SELECT 1 FROM FEE_MANAGEMENT_RATE r WHERE r.BUILDING_ID = b.ID);

-- Bậc giá điện / nước sinh hoạt (số minh hoạ); TIER_NO bắt đầu từ 0 theo @OrderColumn.
INSERT INTO FEE_ELECTRIC_TIER (BUILDING_ID, TIER_NO, UP_TO, UNIT_PRICE)
SELECT b.ID, v.N, v.UP_TO, v.P
FROM BUILDING b
CROSS JOIN (SELECT 0 N, 50 UP_TO, 1893 P FROM DUAL UNION ALL SELECT 1, 100, 1956 FROM DUAL
            UNION ALL SELECT 2, 200, 2271 FROM DUAL UNION ALL SELECT 3, 300, 2860 FROM DUAL
            UNION ALL SELECT 4, 400, 3197 FROM DUAL UNION ALL SELECT 5, NULL, 3302 FROM DUAL) v
WHERE b.CODE = 'SKY01' AND NOT EXISTS (SELECT 1 FROM FEE_ELECTRIC_TIER t WHERE t.BUILDING_ID = b.ID);

INSERT INTO FEE_WATER_TIER (BUILDING_ID, TIER_NO, UP_TO, UNIT_PRICE)
SELECT b.ID, v.N, v.UP_TO, v.P
FROM BUILDING b
CROSS JOIN (SELECT 0 N, 10 UP_TO, 6869 P FROM DUAL UNION ALL SELECT 1, 20, 8110 FROM DUAL
            UNION ALL SELECT 2, 30, 9969 FROM DUAL UNION ALL SELECT 3, NULL, 18318 FROM DUAL) v
WHERE b.CODE = 'SKY01' AND NOT EXISTS (SELECT 1 FROM FEE_WATER_TIER t WHERE t.BUILDING_ID = b.ID);

INSERT INTO FEE_PARKING_RATE (BUILDING_ID, ASSET_CATEGORY_ID, UNIT_PRICE)
SELECT b.ID, c.ID, v.P
FROM BUILDING b
JOIN ASSET_CATEGORY c ON c.BUILDING_ID = b.ID
JOIN (SELECT 'Ô tô' NAME, 1200000 P FROM DUAL UNION ALL SELECT 'Xe máy', 120000 FROM DUAL
      UNION ALL SELECT 'Xe đạp', 30000 FROM DUAL UNION ALL SELECT 'Xe điện', 80000 FROM DUAL) v ON v.NAME = c.NAME
WHERE b.CODE = 'SKY01' AND NOT EXISTS (SELECT 1 FROM FEE_PARKING_RATE r WHERE r.BUILDING_ID = b.ID);

INSERT INTO FEE_OTHER_CHARGE (BUILDING_ID, LINE_NO, NAME, AMOUNT)
SELECT b.ID, 0, 'Phí vệ sinh', 30000 FROM BUILDING b
WHERE b.CODE = 'SKY01' AND NOT EXISTS (SELECT 1 FROM FEE_OTHER_CHARGE o WHERE o.BUILDING_ID = b.ID);

