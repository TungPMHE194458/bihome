MERGE INTO RESIDENT_ACCOUNT ra
USING (
    SELECT r.ID RESIDENT_ID, r.PHONE
    FROM RESIDENT r JOIN BUILDING b ON b.ID = r.BUILDING_ID
    WHERE b.CODE = 'SKY01' AND r.CODE = 'CD000001'
) s
ON (ra.RESIDENT_ID = s.RESIDENT_ID)
WHEN NOT MATCHED THEN
    INSERT (RESIDENT_ID, PHONE, PASSWORD_HASH, STATUS, MUST_CHANGE_PASSWORD, CREATED_BY, UPDATED_BY)
    VALUES (s.RESIDENT_ID, s.PHONE, '$2a$10$y90xVZvYgJjHGP6PUlckV.1Axv100JdPcO1D41r5RPJr7IEGHPVhW', 'ACTIVE', 0,
            'admin', 'admin');

UPDATE RESIDENT r SET r.APP_ACCOUNT_STATUS = 'ACTIVE'
WHERE r.APP_ACCOUNT_STATUS = 'NONE' AND EXISTS (SELECT 1 FROM RESIDENT_ACCOUNT ra WHERE ra.RESIDENT_ID = r.ID);

INSERT INTO RESIDENT_INBOX (RESIDENT_ID, TYPE_CODE, TITLE, BODY, LINK)
SELECT ra.RESIDENT_ID, 'SYSTEM', 'Chào mừng bạn đến với BiHome',
       'Xem thông báo phí, thanh toán VietQR, gửi yêu cầu hỗ trợ và đặt tiện ích ngay trên ứng dụng.', '/'
FROM RESIDENT_ACCOUNT ra JOIN RESIDENT r ON r.ID = ra.RESIDENT_ID
WHERE r.CODE = 'CD000001'
  AND NOT EXISTS (SELECT 1 FROM RESIDENT_INBOX i WHERE i.RESIDENT_ID = ra.RESIDENT_ID AND i.TYPE_CODE = 'SYSTEM');
